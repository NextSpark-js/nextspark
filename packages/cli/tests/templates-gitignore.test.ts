import { test } from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { ensureTemplatesIgnored, trackedTemplatesFiles } from '../src/utils/templates-gitignore.js'

async function project() {
  const root = await mkdtemp(join(tmpdir(), 'nextspark-templates-gitignore-'))
  return { root, cleanup: () => rm(root, { recursive: true, force: true }) }
}

test('the line is appended to an existing .gitignore, once', async () => {
  const { root, cleanup } = await project()
  try {
    await writeFile(join(root, '.gitignore'), '# NextSpark\n.nextspark/')

    assert.equal(ensureTemplatesIgnored(root), true)
    assert.equal(ensureTemplatesIgnored(root), false)

    assert.equal(
      await readFile(join(root, '.gitignore'), 'utf-8'),
      '# NextSpark\n.nextspark/\n\n# Generated by the NextSpark registry build\napp/(templates)/\n'
    )
  } finally {
    await cleanup()
  }
})

test('a .gitignore that already ignores the tree another way is left alone', async () => {
  const { root, cleanup } = await project()
  try {
    await writeFile(join(root, '.gitignore'), 'node_modules/\n/app/(templates)\n')

    assert.equal(ensureTemplatesIgnored(root), false)
    assert.equal(await readFile(join(root, '.gitignore'), 'utf-8'), 'node_modules/\n/app/(templates)\n')
  } finally {
    await cleanup()
  }
})

test('a project with no .gitignore gets one', async () => {
  const { root, cleanup } = await project()
  try {
    assert.equal(ensureTemplatesIgnored(root), true)
    assert.equal(await readFile(join(root, '.gitignore'), 'utf-8'), '# Generated by the NextSpark registry build\napp/(templates)/\n')
  } finally {
    await cleanup()
  }
})

test('tracked files under app/(templates) are listed, and a project outside git has none', async () => {
  const { root, cleanup } = await project()
  try {
    await mkdir(join(root, 'app/(templates)/dashboard'), { recursive: true })
    await writeFile(join(root, 'app/(templates)/dashboard/layout.tsx'), 'export default function L() { return null }\n')

    assert.deepEqual(trackedTemplatesFiles(root), [])

    execFileSync('git', ['init', '-q'], { cwd: root })
    execFileSync('git', ['add', 'app'], { cwd: root })

    assert.deepEqual(trackedTemplatesFiles(root), ['app/(templates)/dashboard/layout.tsx'])
  } finally {
    await cleanup()
  }
})
