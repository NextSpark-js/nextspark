interface FixtureRoute { kind: string, target: string, source: string }

/** The routes of the fixture core's manifest: what a project's app files are compared with. */
const FIXTURE_ROUTES: FixtureRoute[] = [
  { kind: 'layout', target: 'layout.tsx', source: 'export default function Layout({ children }) { return children }\n' },
  { kind: 'page', target: 'dashboard/page.tsx', source: 'export default function Dashboard() { return null }\n' },
  { kind: 'page', target: '(auth)/login/page.tsx', source: 'export default function Login() { return null }\n' },
  { kind: 'route', target: 'api/v1/teams/route.ts', source: 'export async function GET() { return Response.json([]) }\n' },
  { kind: 'route', target: 'api/v1/billing/webhooks/stripe/route.ts', source: 'export async function POST() { return Response.json({}) }\n' },
  { kind: 'route', target: 'api/v1/billing/webhooks/polar/route.ts', source: 'export async function POST() { return Response.json({}) }\n' },
]

const routeSpecifier = (route: FixtureRoute) => `@nextsparkjs/core/routes/${route.target.replace(/\.[^.]+$/, '')}`

/** What the generator emits for a fixture route: an untouched project copy of it is generated. */
function facadeOf(route: FixtureRoute): string {
  const specifier = routeSpecifier(route)
  const exports = route.kind === 'route' ? `export { ${route.source.includes('POST') ? 'POST' : 'GET'} }` : 'export { default }'
  return `// Generated by NextSpark from ${specifier}. Do not edit: regenerated on every build.\n${exports} from ${JSON.stringify(specifier)}\n`
}

const routeOf = (target: string): FixtureRoute => FIXTURE_ROUTES.find(route => route.target === target) as FixtureRoute

/**
 * Install what a 0.1.0-beta.192 core provides for the conversion: its route manifest with the
 * modules, and the real facade emitter (copied, so a fixture can be read without touching the
 * real core), with a stand-in for the generator itself (`prepare` writes a marker, or fails).
 * `prepare` decides what the stand-in does when migrate runs it.
 */
async function installConversionCore(root: string, { version = '0.1.0-beta.192', prefix = '', prepare = 'ok' }: { version?: string, prefix?: string, prepare?: 'ok' | 'fail' } = {}): Promise<void> {
  const core = `${prefix}node_modules/@nextsparkjs/core`
  await write(root, `${core}/package.json`, JSON.stringify({ name: '@nextsparkjs/core', version }))
  for (const file of HOST_SUPPORT) await write(root, `${core}/${file}`, await readFile(join(CORE_SOURCE, file), 'utf8'))
  await write(root, `${core}/src/routes/manifest.json`, JSON.stringify(FIXTURE_ROUTES.map(route => ({ kind: route.kind, target: route.target, specifier: routeSpecifier(route) }))))
  for (const route of FIXTURE_ROUTES) await write(root, `${core}/src/routes/${route.target}`, route.source)
  // The stubs core ships for a project's billing webhook extensions
  for (const provider of ['stripe', 'polar']) await write(root, `${core}/templates/lib/billing/${provider}-webhook-extensions.ts`, `export const ${provider}WebhookExtensions = {}\n`)
  await write(root, `${core}/scripts/build/registry/host/mode.mjs`, "import { existsSync, readFileSync, readdirSync } from 'node:fs'\nimport { join } from 'node:path'\nexport function resolveHostMode({ projectRoot }) {\n  const files = existsSync(join(projectRoot, 'src/app')) ? readdirSync(join(projectRoot, 'src/app'), { recursive: true }).length : 0\n  let valid = false\n  try { valid = JSON.parse(readFileSync(join(projectRoot, '.nextspark/generation.json'), 'utf8')).valid === true } catch {}\n  return files > 0 && !valid ? { mode: 'legacy-app', reason: 'fixture' } : { mode: 'host', reason: 'fixture' }\n}\n")
  await write(root, `${core}/scripts/build/registry/host/prepare-cli.mjs`, prepare === 'ok'
    ? "import { mkdirSync, writeFileSync } from 'node:fs'\nmkdirSync('src/app', { recursive: true })\nmkdirSync('.nextspark', { recursive: true })\nwriteFileSync('src/app/generated-by-prepare.txt', 'ok\\n')\nwriteFileSync('.nextspark/generation.json', JSON.stringify({ valid: true }) + '\\n')\nconsole.log('fixture prepare done')\n"
    : "console.error('route templates/dashboard/page.tsx cannot be planned')\nprocess.exit(1)\n")
  // The emitter loads Next.js and TypeScript from the project: link the ones this repository runs on
  await mkdir(join(root, prefix, 'node_modules'), { recursive: true })
  for (const name of ['next', 'typescript']) {
    const target = dirname(requireHere.resolve(`${name}/package.json`))
    await rm(join(root, prefix, 'node_modules', name), { recursive: true, force: true })
    await symlink(target, join(root, prefix, 'node_modules', name))
  }
}

// A migrate run plans and emits a whole host; GitHub runners need well over the
// ~5 s it takes locally, so the child gets a generous budget before it is killed.
const MIGRATE_CHILD_TIMEOUT_MS = 60_000
const OFFLINE_MIGRATE_ENV = { npm_config_registry: 'http://127.0.0.1:9', NEXTSPARK_MIGRATE_NETWORK_TIMEOUT_MS: '5000' }

function run(root: string, args: string[], env: NodeJS.ProcessEnv = {}) {
  return spawnSync(process.execPath, [cliEntry, 'migrate', ...args], {
    cwd: root,
    encoding: 'utf8',
    timeout: MIGRATE_CHILD_TIMEOUT_MS,
    // The migrate command may inspect an older published core. Tests must
    // never let an accidental lookup escape to the real npm registry, nor
    // wait on pnpm's retries against the dead one: without a cached packument
    // (a CI runner) `pnpm view` retries for about a minute.
    env: { ...process.env, ...OFFLINE_MIGRATE_ENV, ...env },
  })
}

async function runAsync(root: string, args: string[], env: NodeJS.ProcessEnv = {}): Promise<{ status: number, stdout: string, stderr: string }> {
  return new Promise((resolveResult) => {
    const child = spawn(process.execPath, [cliEntry, 'migrate', ...args], {
      cwd: root,
      env: { ...process.env, ...OFFLINE_MIGRATE_ENV, ...env },
      stdio: ['ignore', 'pipe', 'pipe'],
    })
    let stdout = ''
    let stderr = ''
    child.stdout.on('data', chunk => { stdout += chunk })
    child.stderr.on('data', chunk => { stderr += chunk })
    const timeout = setTimeout(() => child.kill('SIGTERM'), MIGRATE_CHILD_TIMEOUT_MS)
    child.on('close', (code) => {
      clearTimeout(timeout)
      resolveResult({ status: code ?? 1, stdout, stderr })
    })
  })
}

async function tarballServer(archive: string): Promise<{
  url: string
  requests: { host: string | undefined, authorization: string | undefined }[]
  close: () => Promise<void>
}> {
  const requests: { host: string | undefined, authorization: string | undefined }[] = []
  const server = createServer(async (request, response) => {
    requests.push({ host: request.headers.host, authorization: request.headers.authorization })
    response.writeHead(200, { 'content-type': 'application/octet-stream' })
    response.end(await readFile(archive))
  })
  await new Promise<void>((resolveListen) => server.listen(0, '127.0.0.1', resolveListen))
  const { port } = server.address() as AddressInfo
  return {
    url: `http://127.0.0.1:${port}/@nextsparkjs/core/-/core.tgz`,
    requests,
    close: () => new Promise((resolveClose, rejectClose) => server.close(error => error ? rejectClose(error) : resolveClose())),
  }
}

