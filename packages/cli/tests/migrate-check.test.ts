import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { after, before, test } from 'node:test'
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'

import { buildCli } from './built-cli.js'

// nextspark migrate --check (#319): the leftovers of an earlier layout, from files only

let cliEntry: string
const roots: string[] = []
before(() => { cliEntry = buildCli() })
after(() => { for (const root of roots) rmSync(root, { recursive: true, force: true }) })

const sha = (text: string) => createHash('sha256').update(text).digest('hex')
const OLD_PROXY = "import { auth } from '@nextsparkjs/core/lib/auth'\nexport async function proxy() { return auth }\nexport const config = { matcher: ['/dashboard/:path*'] }\n"
const FACADE = "export { proxy } from '@nextsparkjs/core/proxy'\nexport const config = { matcher: ['/dashboard/:path*'] }\n"

const BASE: Record<string, string> = {
  'package.json': JSON.stringify({ name: 'project', private: true, dependencies: { next: '16.4.2', '@nextsparkjs/core': '0.1.0-beta.200' } }),
  'next.config.mjs': 'export default {}\n',
  'src/proxy.ts': FACADE,
  '.gitignore': 'node_modules\nsrc/app\n',
  'node_modules/@nextsparkjs/core/package.json': JSON.stringify({ name: '@nextsparkjs/core', version: '0.1.0-beta.200' }),
  'node_modules/@nextsparkjs/core/templates/proxy.ts': FACADE,
  'node_modules/@nextsparkjs/core/scripts/build/registry/host/previous-templates.json': JSON.stringify({ 'proxy.ts': [sha(OLD_PROXY)], 'instrumentation.ts': [] }),
}

/** A committed project: BASE with `files` laid over it (a null removes the base file). */
function project(files: Record<string, string | null> = {}): string {
  const root = mkdtempSync(join(tmpdir(), 'nextspark-migrate-check-'))
  roots.push(root)
  for (const [file, content] of Object.entries({ ...BASE, ...files })) {
    if (content === null) continue
    mkdirSync(dirname(join(root, file)), { recursive: true })
    writeFileSync(join(root, file), content)
  }
  const git = (...args: string[]) => execFileSync('git', args, { cwd: root, stdio: 'ignore' })
  git('init', '--quiet')
  git('config', 'user.email', 'fixture@example.test')
  git('config', 'user.name', 'Fixture')
  git('add', '-f', '.')
  git('commit', '--quiet', '-m', 'fixture')
  return root
}

function check(root: string, args: string[] = []) {
  const result = spawnSync(process.execPath, [cliEntry, 'migrate', '--check', ...args], {
    cwd: root,
    encoding: 'utf8',
    timeout: 60_000,
    env: { ...process.env, npm_config_registry: 'http://127.0.0.1:9', pnpm_config_registry: 'http://127.0.0.1:9' },
  })
  return result
}

function kinds(root: string): string[] {
  const result = check(root, ['--json'])
  const report = JSON.parse(result.stdout) as { obsoleteCopies: { kind: string }[] }
  assert.equal(result.status, report.obsoleteCopies.length > 0 ? 1 : 0, `${result.stdout}\n${result.stderr}`)
  return report.obsoleteCopies.map(finding => finding.kind).sort()
}

const GENERATED_ROUTE = "// Generated by NextSpark from @nextsparkjs/core/routes/layout. Do not edit: regenerated on every build.\nexport { default } from '@nextsparkjs/core/routes/layout'\n"

test('a root-first project with nothing left over exits 0 and says so', () => {
  const root = project()
  const result = check(root)
  assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`)
  assert.match(result.stdout, /No obsolete local copies found/)
  assert.deepEqual(kinds(root), [])
})

test('a generated src/app that git ignores is not a finding; a committed one is', () => {
  assert.deepEqual(kinds(project({ 'src/app/layout.tsx': GENERATED_ROUTE })), ['generated-app-tree'], 'tracked (git add -f in the fixture)')
  const root = project({ 'src/app/layout.tsx': GENERATED_ROUTE })
  execFileSync('git', ['rm', '-r', '-q', '--cached', 'src/app'], { cwd: root })
  execFileSync('git', ['commit', '-q', '-m', 'untrack'], { cwd: root })
  assert.deepEqual(kinds(root), [])
})

test('a committed app/ file without a generation marker is the project’s own, not a finding', () => {
  assert.deepEqual(kinds(project({ 'src/app/page.tsx': 'export default function Page() { return null }\n' })), [])
})

test('a proxy that is an unchanged earlier template is a finding; the current facade and an edited copy are not', () => {
  assert.deepEqual(kinds(project({ 'src/proxy.ts': OLD_PROXY })), ['proxy-copy'])
  assert.deepEqual(kinds(project({ 'src/proxy.ts': `${OLD_PROXY}// my own rule\n` })), [])
  assert.deepEqual(kinds(project({ 'src/proxy.ts': OLD_PROXY, 'proxy.ts': OLD_PROXY })), ['proxy-copy', 'proxy-copy'])
})

test('an instrumentation file that is an earlier template is a finding', () => {
  const old = 'export async function register() {}\n'
  const root = project({
    'instrumentation.ts': old,
    'node_modules/@nextsparkjs/core/scripts/build/registry/host/previous-templates.json': JSON.stringify({ 'proxy.ts': [], 'instrumentation.ts': [sha(old)] }),
  })
  assert.deepEqual(kinds(root), ['instrumentation-copy'])
})

test('without the installed core, entry files are not compared and the output says so', () => {
  const root = project({ 'node_modules/@nextsparkjs/core/package.json': null, 'node_modules/@nextsparkjs/core/templates/proxy.ts': null, 'node_modules/@nextsparkjs/core/scripts/build/registry/host/previous-templates.json': null })
  const result = JSON.parse(check(root, ['--json']).stdout) as { notes: string[] }
  assert.ok(result.notes.some(note => /installed @nextsparkjs\/core was not found/.test(note)), result.notes.join('\n'))
})

test('typescript.ignoreBuildErrors: true in the Next config is a finding; false and a comment are not', () => {
  assert.deepEqual(kinds(project({ 'next.config.mjs': 'export default { typescript: { ignoreBuildErrors: true } }\n' })), ['ignore-build-errors'])
  assert.deepEqual(kinds(project({ 'next.config.mjs': 'export default { typescript: { ignoreBuildErrors: false } }\n' })), [])
  assert.deepEqual(kinds(project({ 'next.config.mjs': '// ignoreBuildErrors: true was removed\nexport default {}\n' })), [])
})

test('patchedDependencies and overrides that target @nextsparkjs packages are findings, in package.json and in pnpm-workspace.yaml', () => {
  const manifest = (extra: Record<string, unknown>) => JSON.stringify({ ...JSON.parse(BASE['package.json']), ...extra })
  assert.deepEqual(kinds(project({ 'package.json': manifest({ pnpm: { patchedDependencies: { '@nextsparkjs/core@0.1.0-beta.200': 'patches/core.patch' } } }) })), ['patched-dependency'])
  assert.deepEqual(kinds(project({ 'package.json': manifest({ pnpm: { overrides: { '@nextsparkjs/core': '0.1.0-beta.190' } } }) })), ['dependency-override'])
  assert.deepEqual(kinds(project({ 'package.json': manifest({ overrides: { react: { '@nextsparkjs/ui': '1.0.0' } } }) })), ['dependency-override'])
  assert.deepEqual(kinds(project({ 'package.json': manifest({ resolutions: { '@nextsparkjs/core': '1.0.0' } }) })), ['dependency-override'])
  assert.deepEqual(kinds(project({ 'pnpm-workspace.yaml': "patchedDependencies:\n  '@nextsparkjs/core@1.0.0': patches/core.patch\noverrides:\n  '@nextsparkjs/ui': 1.0.0\n  left-pad: 1.3.0\n" })), ['dependency-override', 'patched-dependency'])
  // other packages and the unrelated tables stay quiet
  assert.deepEqual(kinds(project({ 'package.json': manifest({ pnpm: { patchedDependencies: { 'left-pad@1.3.0': 'patches/left-pad.patch' }, overrides: { 'left-pad': '1.3.0' } } }) })), [])
  assert.deepEqual(kinds(project({ 'pnpm-workspace.yaml': "packages:\n  - '@nextsparkjs/*'\noverrides:\n  left-pad: 1.3.0\n" })), [])
})

test('--json is stable: hostRoot, obsoleteCopies with kind, file and message, notes; every message names the cleanup section', () => {
  const root = project({ 'next.config.mjs': 'export default { typescript: { ignoreBuildErrors: true } }\n', 'src/proxy.ts': OLD_PROXY })
  const result = check(root, ['--json'])
  assert.equal(result.status, 1)
  const report = JSON.parse(result.stdout)
  assert.deepEqual(Object.keys(report).sort(), ['hostRoot', 'notes', 'obsoleteCopies'])
  assert.equal(report.hostRoot, '.')
  assert.deepEqual(report.obsoleteCopies.map((finding: Record<string, string>) => Object.keys(finding).sort()), [['file', 'kind', 'message'], ['file', 'kind', 'message']])
  for (const finding of report.obsoleteCopies) assert.match(finding.message, /06-upgrade-0x-projects\.md#cleanup-after-migrating/)
  const text = check(root)
  assert.equal(text.status, 1)
  assert.match(text.stdout, /2 obsolete local copies found/)
})

/** The files of a tree with their bytes, to compare before and after. */
function snapshot(root: string): Record<string, string> {
  const files: Record<string, string> = {}
  const visit = (directory: string) => {
    for (const name of readdirSync(directory)) {
      const path = join(directory, name)
      if (statSync(path).isDirectory()) visit(path)
      else files[path.slice(root.length)] = readFileSync(path, 'utf8')
    }
  }
  visit(root)
  return files
}

test('--check writes nothing, in every mode', () => {
  const root = project({
    'next.config.mjs': 'export default { typescript: { ignoreBuildErrors: true } }\n',
    'src/proxy.ts': OLD_PROXY,
    'src/app/layout.tsx': GENERATED_ROUTE,
    'pnpm-workspace.yaml': "overrides:\n  '@nextsparkjs/core': 1.0.0\n",
  })
  const before = snapshot(root)
  for (const args of [[], ['--json']]) check(root, args)
  assert.deepEqual(snapshot(root), before)
  assert.equal(execFileSync('git', ['status', '--porcelain'], { cwd: root, encoding: 'utf8' }), '')
})

test('--check refuses to be combined with an option that writes', () => {
  const root = project()
  for (const flag of ['--yes', '--dry-run', '--rename-entity-slugs']) {
    const result = check(root, [flag])
    assert.equal(result.status, 1, flag)
    assert.match(result.stderr, /--check only reads/)
  }
})

test('--dry-run --json carries the same findings under obsoleteCopies and keeps its exit code', () => {
  const root = project({ 'next.config.mjs': 'export default { typescript: { ignoreBuildErrors: true } }\n' })
  const result = spawnSync(process.execPath, [cliEntry, 'migrate', '--dry-run', '--json'], {
    cwd: root,
    encoding: 'utf8',
    timeout: 60_000,
    env: { ...process.env, npm_config_registry: 'http://127.0.0.1:9', pnpm_config_registry: 'http://127.0.0.1:9', NEXTSPARK_MIGRATE_NO_SIMULATION: '1' },
  })
  assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`)
  const report = JSON.parse(result.stdout)
  assert.deepEqual(report.obsoleteCopies.findings.map((finding: { kind: string }) => finding.kind), ['ignore-build-errors'])
})
