/**
 * QueryClient Health Check
 *
 * A project-owned QueryClient that is not registered is not cleared on sign-in (#374).
 */

import fs from 'fs-extra'
import path from 'path'
import type { HealthCheckResult } from '../index.js'

const SKIP_DIRS = new Set(['node_modules', 'dist', 'build', 'coverage', 'out', 'public', 'storybook-static', 'ios', 'android', '__tests__', 'tests', 'cypress'])
const TEST_FILE = /\.(test|spec|stories)\.[cm]?[jt]sx?$/
const SOURCE = /\.(?:[cm]?[jt]s|[jt]sx)$/
const TYPES = /\.d\.[cm]?ts$/

export async function* sourceFiles(dir: string, root: string): AsyncGenerator<string> {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      // src/app is generated by the registry build
      if (SKIP_DIRS.has(entry.name) || entry.name.startsWith('.') || path.relative(root, full) === path.join('src', 'app')) continue
      yield* sourceFiles(full, root)
    } else if (SOURCE.test(entry.name) && !TYPES.test(entry.name) && !TEST_FILE.test(entry.name)) {
      yield full
    }
  }
}

/** `file:line` of each `new QueryClient(` in files of `root` that never call registerQueryCache. */
export async function findUnregisteredQueryClients(root: string): Promise<string[]> {
  const found: string[] = []
  // ponytail: one check per file, does not follow imports; a client registered from another file is reported
  for await (const file of sourceFiles(root, root)) {
    const text = await fs.readFile(file, 'utf8')
    if (!text.includes('new QueryClient(') || text.includes('registerQueryCache')) continue
    text.split('\n').forEach((line, index) => {
      if (line.includes('new QueryClient(') && !/^\s*(?:\/\/|\*)/.test(line)) {
        found.push(`${path.relative(root, file)}:${index + 1}`)
      }
    })
  }
  return found
}

export async function checkQueryClients(): Promise<HealthCheckResult> {
  const name = 'Query caches'
  const found = await findUnregisteredQueryClients(process.cwd())
  if (found.length === 0) return { name, status: 'pass', message: 'No unregistered QueryClient' }
  const shown = found.slice(0, 3).join(', ') + (found.length > 3 ? ` (+${found.length - 3} more)` : '')
  return {
    name,
    status: 'warn',
    code: 'NS_QUERY_CLIENT_NOT_REGISTERED',
    message: `NS_QUERY_CLIENT_NOT_REGISTERED: a project-owned QueryClient is not cleared on sign-in (${shown})`,
    fix: "In an effect, call registerQueryCache(() => client.clear()) from '@nextsparkjs/core/lib/auth/query-caches' and return its result as the cleanup",
  }
}
