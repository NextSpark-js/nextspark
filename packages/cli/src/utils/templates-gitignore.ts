import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * The line that keeps `app/(templates)` out of git. The registry build rewrites
 * that tree on every run, so a tracked copy only ever drifts from what the build
 * produces - and a fresh checkout would start from the drifted copy.
 */
export const TEMPLATES_GITIGNORE_ENTRY = 'app/(templates)/';

const NEXTSPARK_DIR = ['.nextspark', '.nextspark/', '/.nextspark', '/.nextspark/'];

/**
 * What a sync:app run is about to leave in the project, so the check asks git
 * about those paths rather than about paths of the same shape. A rule narrow
 * enough to cover a stand-in - or one that names the core version a stand-in
 * happens to carry - leaves the real output un-ignored.
 */
export interface GeneratedPathsInRun {
  /** The directory `--backup` copies app/ into, from the project root. */
  appBackupDir?: string;
  /** Files the run leaves under `app/(templates)`, from the project root. */
  templatesFiles?: readonly string[];
}

/** How many of a run's own paths are asked about, past which the shapes answer for the rest. */
const RUN_PROBE_LIMIT = 200;

/**
 * Paths of a few shapes under `dir`, of the depths and names the tree there
 * takes. Asking about one path only answers for a rule as broad as the
 * directory: a rule that names a single file, or a .gitignore inside the tree,
 * covers that path and leaves its siblings behind.
 */
function shapesUnder(dir: string): string[] {
  return [`${dir}/middleware.ts`, `${dir}/dashboard/layout.tsx`, `${dir}/(public)/page.tsx`];
}

/**
 * What sync:app and the registry build leave in a project that has no place in
 * git, grouped under a comment each: the regenerated app/(templates); under
 * .nextspark/ the backups - which can hold a middleware or a config the project
 * never meant to commit - and this machine's sync state; and the copy of app/
 * that --backup takes, one directory per run.
 *
 * `probes` are the paths the entry covers that git is asked about, this run's
 * own where they are known. `ignoredBy` lists lines that already ignore each
 * path, and only stands in outside a repository, where there is no git to ask.
 */
const GENERATED_PATHS: {
  comment: string;
  entry: string;
  probes: (run: GeneratedPathsInRun) => string[];
  ignoredBy: string[];
}[] = [
  {
    comment: '# Generated by the NextSpark registry build',
    entry: TEMPLATES_GITIGNORE_ENTRY,
    probes: ({ templatesFiles = [] }) => [
      ...shapesUnder('app/(templates)'),
      ...templatesFiles.slice(0, RUN_PROBE_LIMIT),
    ],
    ignoredBy: ['app/(templates)', 'app/(templates)/', '/app/(templates)', '/app/(templates)/'],
  },
  {
    comment: '# Backups and state that nextspark sync:app keeps on this machine',
    entry: '.nextspark/backups/',
    probes: () => shapesUnder('.nextspark/backups/2026-01-01T00-00-00-000Z-a1b2c3'),
    ignoredBy: [...NEXTSPARK_DIR, '.nextspark/backups', '.nextspark/backups/', '/.nextspark/backups', '/.nextspark/backups/'],
  },
  {
    comment: '# Backups and state that nextspark sync:app keeps on this machine',
    entry: '.nextspark/sync-state.json',
    probes: () => ['.nextspark/sync-state.json'],
    ignoredBy: [...NEXTSPARK_DIR, '.nextspark/sync-state.json', '/.nextspark/sync-state.json'],
  },
  {
    comment: '# Backups and state that nextspark sync:app keeps on this machine',
    entry: 'app.backup.v*/',
    probes: ({ appBackupDir }) => [
      ...shapesUnder('app.backup.v0.1.0-beta.190.2026-01-01T00-00-00-000Z-a1b2c3'),
      ...(appBackupDir ? shapesUnder(appBackupDir) : []),
    ],
    ignoredBy: [
      'app.backup.v*', 'app.backup.v*/', '/app.backup.v*', '/app.backup.v*/',
      'app.backup.*', 'app.backup.*/', '/app.backup.*', '/app.backup.*/',
    ],
  },
];

/**
 * Which of `paths` git ignores in this project, or null when it can't say: git
 * missing, or a project that is not a repository. `--no-index` keeps the answer
 * about the patterns alone, so a path already tracked - which is what the
 * app/(templates) warning is about - still counts as ignored and the line is
 * not added a second time.
 */
function gitIgnoredPaths(projectRoot: string, paths: string[]): Set<string> | null {
  const asked = spawnSync('git', ['check-ignore', '--no-index', '--stdin', '-z'], {
    cwd: projectRoot,
    input: paths.join('\0'),
    encoding: 'utf-8',
  });
  // 0 is some path ignored and 1 is none; anything else is git declining to answer
  if (asked.error || (asked.status !== 0 && asked.status !== 1)) return null;
  return new Set(asked.stdout.split('\0').filter(Boolean));
}

/**
 * The lines the project's .gitignore lacks for sync:app's output, in the order
 * they would be added. What counts is whether git ends up ignoring every path
 * an entry covers, not whether some line spells the entry: a negation below a
 * broader pattern, as in `app.backup.*` then `!app.backup.v` and a star,
 * un-ignores the backups again, and matching the text alone would read the
 * broader pattern as done. One path left out is enough to add the line, since
 * the line is what covers the whole of what the run writes.
 */
export function missingGitignoreEntries(projectRoot: string, run: GeneratedPathsInRun = {}): string[] {
  const asked = GENERATED_PATHS.map((path) => ({ ...path, probes: path.probes(run) }));
  const ignored = gitIgnoredPaths(projectRoot, asked.flatMap(({ probes }) => probes));
  if (ignored) {
    return asked.filter(({ probes }) => !probes.every((probe) => ignored.has(probe))).map(({ entry }) => entry);
  }

  const gitignorePath = join(projectRoot, '.gitignore');
  const lines = new Set(existsSync(gitignorePath) ? readFileSync(gitignorePath, 'utf-8').split(/\r?\n/).map((line) => line.trim()) : []);
  return GENERATED_PATHS.filter(({ ignoredBy }) => !ignoredBy.some((line) => lines.has(line))).map(({ entry }) => entry);
}

/**
 * Add the lines the project's .gitignore lacks for sync:app's output, creating
 * the file if there is none.
 *
 * @returns The lines added.
 */
export function ensureGeneratedPathsIgnored(projectRoot: string, run: GeneratedPathsInRun = {}): string[] {
  const missing = missingGitignoreEntries(projectRoot, run);
  if (missing.length === 0) return [];

  const gitignorePath = join(projectRoot, '.gitignore');
  const current = existsSync(gitignorePath) ? readFileSync(gitignorePath, 'utf-8') : '';

  const blocks: string[] = [];
  for (const { comment, entry } of GENERATED_PATHS.filter(({ entry }) => missing.includes(entry))) {
    const last = blocks[blocks.length - 1];
    if (last?.startsWith(`${comment}\n`)) {
      blocks[blocks.length - 1] = `${last}${entry}\n`;
    } else {
      blocks.push(`${comment}\n${entry}\n`);
    }
  }

  const separator = current === '' ? '' : current.endsWith('\n') ? '\n' : '\n\n';
  writeFileSync(gitignorePath, `${current}${separator}${blocks.join('\n')}`);
  return missing;
}

/**
 * The files under `app/(templates)` that git tracks in this project. Empty when
 * the project is not a git repository or git is not installed: there is nothing
 * to warn about then.
 */
export function trackedTemplatesFiles(projectRoot: string): string[] {
  try {
    return execFileSync('git', ['ls-files', '--', 'app/(templates)'], {
      cwd: projectRoot,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .split('\n')
      .filter(Boolean);
  } catch {
    return [];
  }
}
