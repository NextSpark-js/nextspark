import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, lstatSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  asBytes,
  everyDirectoryIgnored,
  ignoredByRules,
  ignoreSourcesFor,
  withProjectGitignore,
  type IgnorePattern,
  type IgnoreSources,
} from './gitignore-rules.js';
import type { ProjectFiles } from './core-write-places.js';

/**
 * The line that keeps `app/(templates)` out of git. The registry build rewrites
 * that tree on every run, so a tracked copy only ever drifts from what the build
 * produces - and a fresh checkout would start from the drifted copy.
 */
export const TEMPLATES_GITIGNORE_ENTRY = 'app/(templates)/';

/**
 * The line for `.nextspark/registries`, which keeps what git doesn't track there
 * out of git: what the registry build writes there, it writes again on every run.
 */
export const REGISTRIES_GITIGNORE_ENTRY = '.nextspark/registries/';

/**
 * What sync:app and the registry build write in a project that has no place in
 * git, grouped under a comment each: what the build regenerates, app/(templates)
 * and .nextspark/registries; under .nextspark/ the backups - which can hold a
 * middleware or a config the project never meant to commit - and this machine's
 * sync state; and the copy of app/ that --backup takes, one directory per run.
 * The rest of what they write - app/ and the files at the project root that
 * sync:app keeps, app/globals.css, and the active theme's test fixtures - is the
 * project's to commit.
 *
 * Each is decided as git decides the place it keeps out, not a path under it:
 * a directory git ignores is one it doesn't look into, so whatever is written
 * there, named however and holding any .gitignore of its own, is ignored with
 * it; a directory it doesn't ignore leaves every file in it to the rules for
 * that file, which no sample of names can vouch for. `place` is that directory
 * or file, from the project root; for the copies of app/, whose directories are
 * named as each is created, it is the start of their names, and only a pattern
 * among `coveredBy` counts as ignoring every one of them.
 */
const GENERATED_PATHS: {
  comment: string;
  entry: string;
  place: { path: string; directory: boolean } | { namesStartWith: string; coveredBy: string[] };
}[] = [
  {
    comment: '# Generated by the NextSpark registry build',
    entry: TEMPLATES_GITIGNORE_ENTRY,
    place: { path: 'app/(templates)', directory: true },
  },
  {
    comment: '# Generated by the NextSpark registry build',
    entry: REGISTRIES_GITIGNORE_ENTRY,
    place: { path: '.nextspark/registries', directory: true },
  },
  {
    comment: '# Backups and state that nextspark sync:app keeps on this machine',
    entry: '.nextspark/backups/',
    place: { path: '.nextspark/backups', directory: true },
  },
  {
    comment: '# Backups and state that nextspark sync:app keeps on this machine',
    entry: '.nextspark/sync-state.json',
    place: { path: '.nextspark/sync-state.json', directory: false },
  },
  {
    comment: '# Backups and state that nextspark sync:app keeps on this machine',
    entry: 'app.backup.v*/',
    place: { namesStartWith: 'app.backup.v', coveredBy: ['app.backup.v*', 'app.backup.*'] },
  },
];

/** The directories of the project, besides its root, whose .gitignore can decide one of GENERATED_PATHS. */
const NESTED_GITIGNORE_DIRECTORIES = ['app/', '.nextspark/'];

function isSymlink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

/**
 * Every file under `dir`, from the project root, with a symlink listed as the
 * file git sees it as - `dir` itself too, when it is one.
 */
function filesUnder(projectRoot: string, dir: string): string[] {
  const absolute = join(projectRoot, dir);
  if (isSymlink(absolute)) return [dir];
  if (!existsSync(absolute) || !lstatSync(absolute).isDirectory()) return [];
  return readdirSync(absolute, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? filesUnder(projectRoot, `${dir}/${entry.name}`) : [`${dir}/${entry.name}`]
  );
}

/**
 * The files sync:app and the registry build have left in the project that
 * belong under an entry of GENERATED_PATHS: everything under app/(templates),
 * .nextspark/registries, .nextspark/backups and each app.backup.v directory,
 * and the sync state.
 */
export function generatedPathsOnDisk(projectRoot: string): string[] {
  const appBackups = readdirSync(projectRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name.startsWith('app.backup.v'))
    .map((entry) => entry.name);
  return [
    ...filesUnder(projectRoot, 'app/(templates)'),
    ...filesUnder(projectRoot, '.nextspark/registries'),
    ...filesUnder(projectRoot, '.nextspark/backups'),
    ...(existsSync(join(projectRoot, '.nextspark', 'sync-state.json')) ? ['.nextspark/sync-state.json'] : []),
    ...appBackups.flatMap((dir) => filesUnder(projectRoot, dir)),
  ];
}

/**
 * Which of `paths` git ignores in this project, or null when it can't say: git
 * missing, or a project that is not a repository. `--no-index` keeps the answer
 * about the patterns alone, so a path already tracked - which is what the
 * app/(templates) warning is about - still counts as ignored and the line is
 * not added a second time.
 *
 * Git answers every path in the order it was asked, with the pattern that
 * decided it: none for a path no pattern matches, and one starting with `!` for
 * a negation, both of which leave the path in. Fewer answers than paths is git
 * stopping partway, which is no answer.
 */
function gitIgnoredPaths(projectRoot: string, paths: readonly string[]): Set<string> | null {
  const unique = [...new Set(paths)];
  if (unique.length === 0) return new Set();

  const asked = spawnSync('git', ['check-ignore', '--no-index', '--stdin', '-z', '--verbose', '--non-matching'], {
    cwd: projectRoot,
    input: unique.map((path) => `${path}\0`).join(''),
    encoding: 'utf-8',
    maxBuffer: Infinity,
  });
  // 0 is some path ignored and 1 is none; anything else is git declining to answer
  if (asked.error || (asked.status !== 0 && asked.status !== 1)) return null;

  // Each answer is four fields: the .gitignore, the line, the pattern and the path
  const fields = asked.stdout.split('\0');
  if (fields.length !== unique.length * 4 + 1) return null;
  return new Set(unique.filter((_, index) => {
    const pattern = fields[index * 4 + 2];
    return pattern !== '' && !pattern.startsWith('!');
  }));
}

/** Whether git leaves out the place an entry of GENERATED_PATHS keeps out, and the negation that takes it back when one does. */
function placeIgnored(sources: IgnoreSources, prefix: string, { place }: (typeof GENERATED_PATHS)[number]) {
  if ('path' in place) return ignoredByRules(sources, `${prefix}${asBytes(place.path)}`, place.directory);
  return everyDirectoryIgnored(
    sources,
    `${prefix}${asBytes(place.namesStartWith)}`,
    // Only a pattern of the project root's .gitignore, or one that matches a name at any depth, is anchored where the copies go
    (pattern) => !pattern.negative && place.coveredBy.includes(pattern.body) && (pattern.basenameOnly || pattern.base === prefix),
  );
}

/** `current`, the content of a .gitignore, with `entries` appended under their comments. */
function withEntries(current: string, entries: readonly string[]): string {
  const blocks: string[] = [];
  for (const { comment, entry } of GENERATED_PATHS.filter(({ entry }) => entries.includes(entry))) {
    const last = blocks[blocks.length - 1];
    if (last?.startsWith(`${comment}\n`)) {
      blocks[blocks.length - 1] = `${last}${entry}\n`;
    } else {
      blocks.push(`${comment}\n${entry}\n`);
    }
  }
  const separator = current === '' ? '' : current.endsWith('\n') ? '\n' : '\n\n';
  return `${current}${separator}${blocks.join('\n')}`;
}

/** How a pattern that takes a place back is named: its file, its line, and the pattern as it is written there. */
function namePattern(pattern: IgnorePattern): string {
  const bytes = (text: string) => Buffer.from(text, 'latin1').toString('utf-8');
  return `${bytes(pattern.source)} line ${pattern.line} (${bytes(pattern.text)})`;
}

export interface GitignorePlan {
  /** The lines to add to the project's .gitignore, in the order they are added. */
  add: string[];
  /** The entries whose place git would still pick up with those lines added, each with why. */
  leftForGit: { entry: string; why: string }[];
}

/**
 * What the project's .gitignore lacks for sync:app's output, and what no line
 * added to it can keep out of git, decided as git reads the rules before
 * anything is written: the .gitignore of the project root, of app/ and of
 * .nextspark/, and, in a repository, those above the project, info/exclude and
 * core.excludesFile. Outside a repository, or with no git to ask, it is what
 * git reads once the project is one.
 *
 * An entry is lacking when git doesn't leave its place out. Its line goes at
 * the end of the file, below any negation there; a place git still wouldn't
 * leave out with it is taken back by a .gitignore further down the tree, which
 * git reads over the root's, or the root's .gitignore is a symlink, which git
 * does not read and sync:app does not write through. Its line is not added:
 * it would change nothing.
 */
export function planGitignore(projectRoot: string): GitignorePlan {
  const { sources, prefix } = ignoreSourcesFor(projectRoot, NESTED_GITIGNORE_DIRECTORIES);
  const lacking = GENERATED_PATHS.filter((generated) => !placeIgnored(sources, prefix, generated).ignored).map(({ entry }) => entry);
  if (lacking.length === 0) return { add: [], leftForGit: [] };

  const symlinked = gitignoreIsSymlink(projectRoot);
  const gitignorePath = join(projectRoot, '.gitignore');
  const current = !symlinked && existsSync(gitignorePath) ? readFileSync(gitignorePath, 'utf-8') : '';
  const withLines = withProjectGitignore(sources, prefix, symlinked ? null : asBytes(withEntries(current, lacking)));

  const add: string[] = [];
  const leftForGit: GitignorePlan['leftForGit'] = [];
  for (const generated of GENERATED_PATHS.filter(({ entry }) => lacking.includes(entry))) {
    const { ignored, takenBackBy } = placeIgnored(withLines, prefix, generated);
    if (ignored) {
      add.push(generated.entry);
    } else {
      leftForGit.push({
        entry: generated.entry,
        why: symlinked
          ? "the project's .gitignore is a symlink, which git does not read, so no line there keeps it out of git"
          : takenBackBy
            ? `${namePattern(takenBackBy)} takes it back, and git reads that over a line the project's .gitignore adds`
            : "no line the project's .gitignore adds keeps it out of git",
      });
    }
  }
  return { add, leftForGit };
}

/** The lines the project's .gitignore lacks for sync:app's output that adding them makes git leave out, in the order they are added. */
export function missingGitignoreEntries(projectRoot: string): string[] {
  return planGitignore(projectRoot).add;
}

/**
 * The paths among `paths` that git does not ignore in this project, in the order
 * given; none outside a repository. With the entries in a .gitignore git reads at
 * the project root, only a .gitignore further down the tree, which git reads
 * after it, can leave one of sync:app's paths in.
 */
export function unignoredPaths(projectRoot: string, paths: readonly string[]): string[] {
  const ignored = gitIgnoredPaths(projectRoot, paths);
  return ignored ? paths.filter((path) => !ignored.has(path)) : [];
}

/**
 * Whether the project's .gitignore is a symlink. Git does not read a .gitignore
 * through a symlink, so a line written to the file it points at ignores nothing.
 */
export function gitignoreIsSymlink(projectRoot: string): boolean {
  try {
    return lstatSync(join(projectRoot, '.gitignore')).isSymbolicLink();
  } catch {
    return false;
  }
}

/**
 * Add the lines the project's .gitignore lacks for sync:app's output, creating
 * the file if there is none: those `planGitignore` adds, written with `files` -
 * sync:app's are core's guarded calls. A .gitignore that is a symlink is left as
 * it is.
 *
 * @returns The lines added.
 */
export function ensureGeneratedPathsIgnored(projectRoot: string, files: Pick<ProjectFiles, 'writeFileSync'>): string[] {
  const { add } = planGitignore(projectRoot);
  if (add.length === 0 || gitignoreIsSymlink(projectRoot)) return [];

  const gitignorePath = join(projectRoot, '.gitignore');
  const current = existsSync(gitignorePath) ? readFileSync(gitignorePath, 'utf-8') : '';
  files.writeFileSync(gitignorePath, withEntries(current, add));
  return add;
}

/**
 * The files under `app/(templates)` that git tracks in this project. Empty when
 * the project is not a git repository or git is not installed: there is nothing
 * to warn about then.
 */
export function trackedTemplatesFiles(projectRoot: string): string[] {
  try {
    return execFileSync('git', ['ls-files', '--', 'app/(templates)'], {
      cwd: projectRoot,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .split('\n')
      .filter(Boolean);
  } catch {
    return [];
  }
}
