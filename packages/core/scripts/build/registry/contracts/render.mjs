/**
 * Render the portable contracts module (#203 stage 7b): the DTO types and zod schemas of the
 * project's entities and the API response envelopes, as TypeScript sources.
 *
 * The output imports `zod` and nothing else - no Node built-ins, no server code, no registries -
 * so a React Native app can import it. It is a pure function of its input, byte for byte:
 * no timestamps, entities in slug order, fields in config order.
 *
 * ```
 * src/index.ts               export * from the envelope, the shared field schemas and the entities
 * src/envelope.ts            ApiSuccessResponse / ApiListResponse / ApiErrorResponse (+ zod schemas)
 * src/fields.ts              the schemas several field types share (address, uploaded file, media reference)
 * src/schema/*.ts            core's portable schema sources, copied verbatim (lib/entities/portable/)
 * src/entities/index.ts      export * of every entity module
 * src/entities/<slug>.ts     the entity descriptor, <Entity>, Create<Entity>Input, Update<Entity>Input, their schemas,
 *                            one enum per option field
 * ```
 *
 * Request schemas ARE the server's: each entity module calls `generateEntitySchemas` from the copied
 * `src/schema/schema-generator.ts` on a literal descriptor of the entity, so what a client validates is what
 * the server enforces. Response DTOs are rendered from the columns the handlers select (`entityResponseSystemColumns`,
 * `taxonomyResponseFields`, evaluated from the same response-shape.ts the handlers import) and, for numbers, from
 * what the `pg` driver delivers for the column's SQL type (`pgWireKind`).
 *
 * @module core/scripts/build/registry/contracts/render
 */

import { wireKind } from './read-entities.mjs'
import { PORTABLE_FILES } from './portable.mjs'

export const CONTRACTS_HEADER = '// Generated by NextSpark (nextspark prepare). Do not edit: regenerated on every prepare.'

const quote = value => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`

/** `in-progress` -> `InProgress`, `visitDays` -> `VisitDays`. */
export function pascal(text) {
  const words = String(text).replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).filter(Boolean)
  const joined = words.map(word => word[0].toUpperCase() + word.slice(1)).join('')
  return /^[A-Za-z]/.test(joined) ? joined : `Entity${joined}`
}

const camel = text => {
  const value = pascal(text)
  return value[0].toLowerCase() + value.slice(1)
}

/** The singular form of a plural slug, for entities that do not name themselves (`categories` -> `category`). */
export function singularize(slug) {
  if (/ies$/.test(slug)) return slug.replace(/ies$/, 'y')
  if (/(?:ss|us|is)$/.test(slug)) return slug
  if (/(?:ches|shes|xes|sses|zes)$/.test(slug)) return slug.replace(/es$/, '')
  return slug.replace(/s$/, '')
}

/** The names an entity module exports, from the entity's contract. */
export function entityNames(contract) {
  const singular = contract.singular && /[A-Za-z]/.test(contract.singular) ? contract.singular : singularize(contract.slug)
  const base = pascal(singular)
  return {
    base,
    schema: `${camel(base)}Schema`,
    create: `Create${base}Input`,
    createSchema: `create${base}InputSchema`,
    update: `Update${base}Input`,
    updateSchema: `update${base}InputSchema`,
    apiPath: `${camel(contract.slug)}ApiPath`,
    entity: `${camel(base)}Entity`,
    createShape: `${camel(base)}CreateShape`,
    updateShape: `${camel(base)}UpdateShape`,
    schemas: `${camel(base)}Schemas`,
  }
}

const enumNames = (names, field, multi) => {
  const stem = `${names.base}${pascal(field.name)}${multi ? 'Option' : ''}`
  return { type: stem, schema: `${camel(stem)}Schema` }
}

const literalExpression = value => (typeof value === 'number' ? `z.literal(${value})` : `z.literal(${quote(value)})`)

function enumExpression(values) {
  if (values.every(value => typeof value === 'string')) return `z.enum([${values.map(quote).join(', ')}])`
  return values.length === 1 ? literalExpression(values[0]) : `z.union([${values.map(literalExpression).join(', ')}])`
}

/**
 * The zod expression of a field's value. `side` is `response` (what the handler returns: numbers follow the SQL column,
 * `shape.pgWireKind`) or `request` (what a client should send, for the input types only: the server's own schema
 * validates, and accepts a number or a numeric string).
 */
function valueExpression(field, names, { side, contract, shape, inlineEnums = false }) {
  const wire = wireKind(field)
  switch (wire.kind) {
    case 'string':
      return 'z.string()'
    case 'number': {
      if (side === 'request') return 'z.union([z.number(), z.string()])'
      const column = contract.columnTypes?.[field.name]
      const delivered = column ? shape.pgWireKind(column) : null
      if (delivered === 'string') return 'z.string()'
      if (delivered === 'number') return 'z.number()'
      return 'z.union([z.number(), z.string()])'
    }
    case 'address':
      return 'addressSchema'
    case 'media':
      return 'mediaRefSchema'
    case 'image':
      return 'z.union([z.string(), z.array(fileObjectSchema)])'
    case 'files':
      return 'z.array(fileObjectSchema)'
    case 'id-list':
      return side === 'request' ? 'z.array(z.string())' : 'z.union([z.array(z.string()), z.string()])'
    case 'boolean':
      return 'z.boolean()'
    case 'tuple':
      return 'z.tuple([z.number(), z.number()])'
    case 'string-array':
      return 'z.array(z.string())'
    case 'enum':
      return inlineEnums ? enumExpression(wire.values) : enumNames(names, field, false).schema
    case 'enum-array':
      return `z.array(${inlineEnums ? enumExpression(wire.values) : enumNames(names, field, true).schema})`
    default:
      return 'z.unknown()'
  }
}

/** Every name the entity module declares, to catch two entities that would export the same one. */
export function exportedNames(contract) {
  const names = entityNames(contract)
  const exported = [names.base, names.schema, names.create, names.createSchema, names.update, names.updateSchema, names.apiPath, names.entity]
  for (const field of contract.fields) {
    const wire = wireKind(field)
    if (wire.kind === 'enum') exported.push(enumNames(names, field, false).type, enumNames(names, field, false).schema)
    if (wire.kind === 'enum-array') exported.push(enumNames(names, field, true).type, enumNames(names, field, true).schema)
  }
  return exported
}

const SHARED_FIELD_SCHEMAS = ['addressSchema', 'fileObjectSchema', 'mediaRefSchema']

const usesSharedSchema = (field, name) => {
  const kind = wireKind(field).kind
  return (name === 'addressSchema' && kind === 'address') || (name === 'mediaRefSchema' && kind === 'media') || (name === 'fileObjectSchema' && (kind === 'image' || kind === 'files'))
}

/** Every name the envelope and the shared field schemas export: no entity may export one too. */
export const SHARED_EXPORTS = [
  'apiInfoSchema', 'ApiInfo', 'paginationInfoSchema', 'PaginationInfo', 'ApiSuccessResponse', 'ApiListResponse', 'ApiErrorResponse', 'ApiResponse',
  'apiSuccessResponseSchema', 'apiListResponseSchema', 'apiErrorResponseSchema',
  'addressSchema', 'Address', 'fileObjectSchema', 'FileObject', 'mediaRefSchema', 'MediaRef',
]

const propertyLiteral = value => (typeof value === 'string' ? quote(value) : String(value))

const identifierKey = name => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : quote(name))

/** One field of a descriptor as a literal (`api` is the top-level fields' only: child fields have none). */
function fieldLiteral(field, { api }) {
  const parts = [`name: ${quote(field.name)}`, `type: ${quote(field.type)}`, `required: ${field.required}`]
  if (field.defaultValue) parts.push(`defaultValue: ${propertyLiteral(field.defaultValue.value)}`)
  for (const key of ['min', 'max', 'maxLength']) if (field[key] !== undefined) parts.push(`${key}: ${field[key]}`)
  if (field.optionDescriptors) parts.push(`options: [${field.optionDescriptors.map(option => `{ value: ${propertyLiteral(option.value)}${option.label ? `, label: ${quote(option.label)}` : ''} }`).join(', ')}]`)
  parts.push(`display: { label: ${quote(field.label)} }`)
  if (api) parts.push(`api: { readOnly: ${field.readOnly} }`)
  return `{ ${parts.join(', ')} }`
}

/** The literal descriptor of the entity `generateEntitySchemas` is run on. */
function descriptorLiteral(contract, names) {
  const singular = contract.singular && /[A-Za-z]/.test(contract.singular) ? contract.singular : singularize(contract.slug)
  const lines = [`export const ${names.entity} = {`, `  slug: ${quote(contract.slug)},`, `  names: { singular: ${quote(singular)} },`, '  fields: [', ...contract.fields.map(field => `    ${fieldLiteral(field, { api: true })},`), '  ],']
  if (contract.builder) lines.push('  builder: { enabled: true },')
  if (contract.softDelete) lines.push('  table: { softDelete: true },')
  if (contract.taxonomies.length > 0) lines.push(`  taxonomies: { enabled: true, types: [${contract.taxonomies.map(type => `{ type: ${quote(type.type)}, field: ${quote(type.field)} }`).join(', ')}] },`)
  if (contract.childEntities) {
    lines.push('  childEntities: {')
    for (const [name, child] of Object.entries(contract.childEntities)) lines.push(`    ${identifierKey(name)}: {`, `      table: ${quote(child.table)},`, '      fields: [', ...child.fields.map(field => `        ${fieldLiteral(field, { api: false })},`), '      ],', '    },')
    lines.push('  },')
  }
  lines.push('} satisfies EntityConfig')
  return lines
}

/** The module of one entity. `shape` is the evaluated response-shape.ts of the core the contracts are generated with. */
export function renderEntity(contract, { source, shape } = {}) {
  const names = entityNames(contract)
  const isSystem = name => ['id', 'createdAt', 'updatedAt', 'userId', 'teamId'].includes(name)
  const own = new Set(contract.fields.map(field => field.name))
  const writable = contract.fields.filter(field => !field.readOnly && !isSystem(field.name))
  const systemColumns = shape.entityResponseSystemColumns({ builder: { enabled: contract.builder }, table: { softDelete: contract.softDelete } }, { includeSoftDelete: true })
  const taxonomyFields = shape.taxonomyResponseFields({ taxonomies: { enabled: contract.taxonomies.length > 0, types: contract.taxonomies } })
  // The shared schemas any field needs, a child row's fields included (their input types use them too)
  const everyField = [...contract.fields, ...Object.values(contract.childEntities ?? {}).flatMap(child => child.fields)]
  const shared = SHARED_FIELD_SCHEMAS.filter(name => everyField.some(field => usesSharedSchema(field, name)))
  const fromShape = ['builderBlockSchema', 'taxonomyTermSchema', 'metasResponseSchema', 'childrenResponseSchema']
  const usedFromShape = ['metasResponseSchema', 'childrenResponseSchema', ...(contract.builder ? ['builderBlockSchema'] : []), ...(taxonomyFields.length > 0 ? ['taxonomyTermSchema'] : [])]
    .filter((name, index, all) => fromShape.includes(name) && all.indexOf(name) === index).sort()

  const lines = [CONTRACTS_HEADER]
  if (source) lines.push(`// Source: ${source}`)
  for (const warning of contract.warnings) lines.push(`// Warning: ${warning}`)
  lines.push('', "import * as z from 'zod'", "import type { EntityConfig } from '../schema/types'", "import { generateEntitySchemas } from '../schema/schema-generator'", `import { ${usedFromShape.join(', ')} } from '../schema/response-shape'`)
  if (shared.length > 0) lines.push(`import { ${shared.join(', ')} } from '../fields'`)
  lines.push('', `export const ${names.apiPath} = ${quote(`/api/v1/${contract.slug}`)}`, '')

  lines.push('/** The entity as the server sees it: the request schemas below are generated from it by the server\'s own generator. */', ...descriptorLiteral(contract, names), '', `const ${names.schemas} = generateEntitySchemas(${names.entity})`, '')

  for (const field of contract.fields) {
    const wire = wireKind(field)
    if (wire.kind !== 'enum' && wire.kind !== 'enum-array') continue
    const declared = enumNames(names, field, wire.kind === 'enum-array')
    lines.push(`export const ${declared.schema} = ${enumExpression(wire.values)}`, `export type ${declared.type} = z.infer<typeof ${declared.schema}>`, '')
  }

  // Response: the columns the handlers select, in their order, then the configured fields, the taxonomy expansions and the optional expansions
  const response = []
  const systemType = { blocks: 'z.array(builderBlockSchema).nullish()', deletedAt: 'z.string().nullish()', deletedBy: 'z.string().nullish()' }
  for (const column of systemColumns) if (!own.has(column) || column === 'id') response.push(`  ${column}: ${systemType[column] ?? 'z.string()'},`)
  for (const field of contract.fields.filter(field => field.name !== 'id')) {
    const present = field.required || field.hasDefault
    response.push(`  ${field.name}: ${valueExpression(field, names, { side: 'response', contract, shape })}${present ? '' : '.nullish()'},`)
  }
  for (const field of taxonomyFields) if (!own.has(field)) response.push(`  ${field}: z.array(taxonomyTermSchema),`)
  response.push('  metas: metasResponseSchema.optional(),', '  children: childrenResponseSchema.optional(),')
  lines.push(`export const ${names.schema} = z.object({`, ...response, '})', `export type ${names.base} = z.infer<typeof ${names.schema}>`, '')

  // Requests: the server's schemas, typed by what a client should send
  // A child row is typed from the child's own fields, with the parent's semantics (required unless it has a default,
  // enum options, numbers as a number or a numeric string) and an optional `id` (an existing row); the server's schema
  // rejects the rows these types reject
  const childRow = child => `z.object({ id: z.string().optional(), ${child.fields.map(field => `${identifierKey(field.name)}: ${valueExpression(field, names, { side: 'request', contract, shape, inlineEnums: true })}${field.required && !field.hasDefault ? '' : '.nullish()'}`).join(', ')} })`
  const childKeys = contract.childEntities ? [`  children: z.object({ ${Object.entries(contract.childEntities).map(([name, child]) => `${identifierKey(name)}: z.array(${childRow(child)}).optional()`).join(', ')} }).optional(),`] : []
  const builderKeys = [...(contract.builder ? ['  blocks: z.unknown().optional(),', '  settings: z.unknown().optional(),'] : []), ...childKeys]
  const create = writable.map(field => `  ${field.name}: ${valueExpression(field, names, { side: 'request', contract, shape })}${field.required && !field.hasDefault ? '' : '.nullish()'},`)
  const update = writable.map(field => `  ${field.name}: ${valueExpression(field, names, { side: 'request', contract, shape })}${field.required ? '.optional()' : '.nullish()'},`)
  lines.push('// Types only: what a client should send. The schemas exported below are the server\'s, which also accept what it normalizes', `// (numeric strings, empty values) and, on update, the read-only columns of a row fetched earlier.`)
  lines.push(`const ${names.createShape} = z.object({`, ...create, ...builderKeys, '})', `const ${names.updateShape} = z.object({`, ...update, ...builderKeys, '})', '')
  lines.push(`export type ${names.create} = z.input<typeof ${names.createShape}>`, `export const ${names.createSchema} = ${names.schemas}.create as unknown as z.ZodType<${names.create}>`, '')
  lines.push(`export type ${names.update} = z.input<typeof ${names.updateShape}>`, `export const ${names.updateSchema} = ${names.schemas}.update as unknown as z.ZodType<${names.update}>`, '')
  return lines.join('\n')
}

/** The API response envelopes, exactly what `createApiResponse` / `createApiError` put on the wire. */
export function renderEnvelope() {
  return `${CONTRACTS_HEADER}

import * as z from 'zod'

/** \`info\` of every response: the timestamp, plus whatever the endpoint adds (pagination, \`created\`). */
export const apiInfoSchema = z.looseObject({ timestamp: z.string() })
export type ApiInfo = z.infer<typeof apiInfoSchema>

/** What a list endpoint adds to \`info\`. */
export const paginationInfoSchema = z.object({
  page: z.number(),
  limit: z.number(),
  total: z.number(),
  totalPages: z.number(),
  hasNextPage: z.boolean(),
  hasPrevPage: z.boolean(),
})
export type PaginationInfo = z.infer<typeof paginationInfoSchema>

export interface ApiSuccessResponse<T> {
  success: true
  data: T
  info: ApiInfo
}

export interface ApiListResponse<T> {
  success: true
  data: T[]
  info: ApiInfo & PaginationInfo
}

export interface ApiErrorResponse {
  success: false
  error: string
  code: string
  details?: unknown
  info?: ApiInfo
}

export type ApiResponse<T> = ApiSuccessResponse<T> | ApiErrorResponse

export function apiSuccessResponseSchema<T extends z.ZodType>(data: T) {
  return z.object({ success: z.literal(true), data, info: apiInfoSchema })
}

export function apiListResponseSchema<T extends z.ZodType>(item: T) {
  return z.object({ success: z.literal(true), data: z.array(item), info: apiInfoSchema.extend(paginationInfoSchema.shape) })
}

export const apiErrorResponseSchema = z.object({
  success: z.literal(false),
  error: z.string(),
  code: z.string(),
  details: z.unknown().optional(),
  info: apiInfoSchema.optional(),
})
`
}

/** The schemas several entities' field types share: the server's own (schema/schema-generator.ts, schema/media-ref.ts). */
export function renderFields() {
  return `${CONTRACTS_HEADER}

import * as z from 'zod'
import { addressSchema, fileObjectSchema } from './schema/schema-generator'
import { mediaRefSchema } from './schema/media-ref'

export { addressSchema, fileObjectSchema, mediaRefSchema }

/** \`address\` fields. */
export type Address = z.infer<typeof addressSchema>

/** One uploaded file: the items of \`file\`, \`video\`, \`audio\` and multi-\`image\` fields. */
export type FileObject = z.infer<typeof fileObjectSchema>

/** \`media-library\` fields: a plain URL (legacy) or the media id with its url. */
export type MediaRef = z.infer<typeof mediaRefSchema>
`
}

/**
 * Every file of the contracts module for these entity contracts (`{ contract, source }` in slug order) and the
 * portable sources (`{ path, content }` from `readPortableSources`), as `{ path, content }` relative to the module
 * root, sorted by path.
 */
export function renderContracts(entities, { portable = [], shape } = {}) {
  const files = [...portable, { path: 'src/envelope.ts', content: renderEnvelope() }, { path: 'src/fields.ts', content: renderFields() }]
  for (const { contract, source } of entities) files.push({ path: `src/entities/${contract.slug}.ts`, content: renderEntity(contract, { source, shape }) })
  const entityExports = entities.map(({ contract }) => `export * from './${contract.slug}'`)
  files.push({ path: 'src/entities/index.ts', content: `${CONTRACTS_HEADER}\n\n${entityExports.length > 0 ? `${entityExports.join('\n')}\n` : 'export {}\n'}` })
  files.push({ path: 'src/index.ts', content: `${CONTRACTS_HEADER}\n\nexport * from './envelope'\nexport * from './fields'\nexport * from './entities'\n` })
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
}

