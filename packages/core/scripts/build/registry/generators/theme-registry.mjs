/**
 * Theme Registry Generator
 *
 * Generates theme-registry.ts
 *
 * @module core/scripts/build/registry/generators/theme-registry
 */

import { join } from 'path'
import { convertCorePath } from '../config.mjs'

/**
 * Generate the theme registry file
 * @param {Array} themes - Discovered themes
 * @param {object} config - Configuration object from getConfig()
 * @returns {string} Generated TypeScript content
 */
import { toSafeIdentifier } from './identifier.mjs'

export function generateThemeRegistry(themes, config) {
  const outputFilePath = join(config.outputDir, 'theme-registry.ts')
  // Generate theme config imports
  const themeImports = themes.map(theme =>
    theme.exportName
      ? `import { ${theme.exportName} } from '${theme.configPath}'`
      : `import { ${theme.name}ThemeConfig } from '${theme.configPath}'`
  ).join('\n')

  // Generate dashboard config imports
  const dashboardImports = themes
    .filter(theme => theme.hasDashboardConfig)
    .map(theme => {
      const safeThemeName = toSafeIdentifier(theme.name)
      return `import { ${theme.dashboardConfigExportName || 'DASHBOARD_CONFIG'} as ${safeThemeName}DashboardConfig } from '${theme.dashboardConfigPath}'`
    }).join('\n')

  // Generate app config imports
  const appImports = themes
    .filter(theme => theme.hasAppConfig)
    .map(theme => {
      const safeThemeName = toSafeIdentifier(theme.name)
      return `import { ${theme.appConfigExportName || 'APP_CONFIG_OVERRIDES'} as ${safeThemeName}AppConfig } from '${theme.appConfigPath}'`
    }).join('\n')

  // Generate dev config imports (development-only settings)
  const devImports = themes
    .filter(theme => theme.hasDevConfig)
    .map(theme => {
      const safeThemeName = toSafeIdentifier(theme.name)
      return `import { ${theme.devConfigExportName || 'DEV_CONFIG_OVERRIDES'} as ${safeThemeName}DevConfig } from '${theme.devConfigPath}'`
    }).join('\n')

  // Note: Scheduled actions are NOT imported here because they contain server-only code.
  // The theme registry is used by client components, so we only store the path.
  // Use the scheduledActionsPath to dynamically import where needed (server-side only).

  const imports = [themeImports, dashboardImports, appImports, devImports].filter(Boolean).join('\n')

  const registryEntries = themes.map(theme => {
    const configName = theme.exportName || `${theme.name}ThemeConfig`
    const safeThemeName = toSafeIdentifier(theme.name)
    const dashboardConfigName = theme.hasDashboardConfig ? `${safeThemeName}DashboardConfig` : 'null'
    const appConfigName = theme.hasAppConfig ? `${safeThemeName}AppConfig` : 'null'
    const devConfigName = theme.hasDevConfig ? `${safeThemeName}DevConfig` : 'null'

    return `  '${theme.name}': {
    name: '${theme.name}',
    config: ${configName},
    hasComponents: ${theme.hasComponents},
    hasStyles: ${theme.hasStyles},
    hasAssets: ${theme.hasAssets || false},
    hasMessages: ${theme.hasMessages || false},
    hasDashboardConfig: ${theme.hasDashboardConfig || false},
    dashboardConfig: ${dashboardConfigName},
    hasAppConfig: ${theme.hasAppConfig || false},
    appConfig: ${appConfigName},
    hasDevConfig: ${theme.hasDevConfig || false},
    devConfig: ${devConfigName},
    hasScheduledActions: ${theme.hasScheduledActions || false},
    scheduledActionsPath: ${theme.scheduledActionsPath ? `'${theme.scheduledActionsPath}'` : 'null'},
    componentsPath: ${theme.componentsPath ? `'${theme.componentsPath}'` : 'null'},
    stylesPath: ${theme.stylesPath ? `'${theme.stylesPath}'` : 'null'},
    assetsPath: ${theme.assetsPath ? `'${theme.assetsPath}'` : 'null'},
    messagesPath: ${theme.messagesPath ? `'${theme.messagesPath}'` : 'null'},
    entities: ${JSON.stringify(theme.entities || [], null, 6).replace(/^/gm, '    ')},
    routeFiles: ${JSON.stringify(theme.routeFiles || [], null, 6).replace(/^/gm, '    ')},
    plugins: [${(theme.plugins || []).map(p => `'${p}'`).join(', ')}]
  }`
  }).join(',\n')

  return `/**
 * Auto-generated Theme Registry
 *
 * Generated at: ${new Date().toISOString()}
 * Themes discovered: ${themes.length}
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

${imports}
import type { ThemeConfig } from '${convertCorePath('@/core/types/theme', outputFilePath, config)}'
import type { DevConfig } from '${convertCorePath('@/core/lib/config/types', outputFilePath, config)}'

export interface ThemeEntity {
  name: string
  exportName: string
  configPath: string
  actualConfigFile: string
  relativePath: string
  depth: number
  parent: string | null
  children: string[]
  hasComponents: boolean
  hasHooks: boolean
  hasMigrations: boolean
  hasMessages: boolean
  hasAssets: boolean
  messagesPath: string
  pluginContext: { pluginName: string } | null
  themeContext: { themeName: string } | null
  source: string
}

export interface ThemeRouteFile {
  path: string
  filePath: string
  relativePath: string
  methods: string[]
  isRouteFile: boolean
  theme: string
}

export interface ThemeRegistryEntry {
  name: string
  config: ThemeConfig
  hasComponents: boolean
  hasStyles: boolean
  hasAssets: boolean
  hasMessages: boolean
  hasDashboardConfig: boolean
  dashboardConfig: any | null
  hasAppConfig: boolean
  appConfig: any | null
  hasDevConfig: boolean
  devConfig: DevConfig | null
  hasScheduledActions: boolean
  scheduledActionsPath: string | null
  componentsPath: string | null
  stylesPath: string | null
  assetsPath: string | null
  messagesPath: string | null
  entities: ThemeEntity[]
  routeFiles: ThemeRouteFile[]
  plugins: string[]
}

export const THEME_REGISTRY: Record<string, ThemeRegistryEntry> = {
${registryEntries}
}

export type ThemeName = keyof typeof THEME_REGISTRY

/**
 * Theme registry metadata
 */
export const THEME_METADATA = {
  totalThemes: ${themes.length},
  themesWithComponents: ${themes.filter(t => t.hasComponents).length},
  themesWithStyles: ${themes.filter(t => t.hasStyles).length},
  themesWithAssets: ${themes.filter(t => t.hasAssets).length},
  themesWithMessages: ${themes.filter(t => t.hasMessages).length},
  themesWithDashboardConfig: ${themes.filter(t => t.hasDashboardConfig).length},
  themesWithAppConfig: ${themes.filter(t => t.hasAppConfig).length},
  themesWithDevConfig: ${themes.filter(t => t.hasDevConfig).length},
  themesWithScheduledActions: ${themes.filter(t => t.hasScheduledActions).length},
  themesWithEntities: ${themes.filter(t => t.entities && t.entities.length > 0).length},
  themesWithRoutes: ${themes.filter(t => t.routeFiles && t.routeFiles.length > 0).length},
  themesUsingPlugins: ${themes.filter(t => t.plugins && t.plugins.length > 0).length},
  totalThemeEntities: ${themes.reduce((sum, t) => sum + (t.entities?.length || 0), 0)},
  totalThemeRoutes: ${themes.reduce((sum, t) => sum + (t.routeFiles?.length || 0), 0)},
  generatedAt: '${new Date().toISOString()}',
  themes: [${themes.map(t => `'${t.name}'`).join(', ')}]
}
`
}

/**
 * Generate the client-safe theme registry file
 *
 * A root-first project contributes at most one theme, and the client only
 * ever needs that theme's own ThemeConfig: `ThemeProvider` reads `styles`
 * (to run `applyThemeStyles`) and `components.overrides`/`custom` (for the
 * import resolver). It has no use for `dashboardConfig`, `appConfig`,
 * `devConfig`, `entities` or `routeFiles` - those are server-only and can be
 * tens of KB of generated navigation/permission/dev-keyring data. Importing
 * theme-registry.ts for those few fields used to pull all of it into every
 * client bundle (#207); this file exists so the client only imports what it
 * reads.
 *
 * @param {Array} themes - Discovered themes
 * @param {object} config - Configuration object from getConfig()
 * @returns {string} Generated TypeScript content
 */
export function generateThemeRegistryClient(themes, config) {
  const outputFilePath = join(config.outputDir, 'theme-registry.client.ts')

  const themeImports = themes.map(theme =>
    theme.exportName
      ? `import { ${theme.exportName} } from '${theme.configPath}'`
      : `import { ${theme.name}ThemeConfig } from '${theme.configPath}'`
  ).join('\n')

  const registryEntries = themes.map(theme => {
    const configName = theme.exportName || `${theme.name}ThemeConfig`
    return `  '${theme.name}': ${configName}`
  }).join(',\n')

  // A project without config/theme.config.ts is valid while a project is being
  // scaffolded. Do not emit an import in that case: apart from keeping the
  // empty registry self-contained, it avoids resolving a type-only project
  // alias that does not exist yet.
  const themeConfigType = themes.length > 0
    ? `import type { ThemeConfig } from '${convertCorePath('@/core/types/theme', outputFilePath, config)}'`
    : 'type ThemeConfig = never'

  return `/**
 * Client-Safe Theme Registry
 *
 * Generated at: ${new Date().toISOString()}
 * Themes discovered: ${themes.length}
 *
 * Holds only each theme's own ThemeConfig - no dashboard config, app config,
 * dev config, entities, or route files. Those stay server-only in
 * theme-registry.ts. Import this file from client components; import
 * theme-registry.ts from server code.
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

${themeImports}
${themeConfigType}

export const THEME_REGISTRY: Record<string, ThemeConfig> = {
${registryEntries}
}
`
}

/**
 * Generate the public application-config input used by client components.
 *
 * The synchronous server config loader intentionally reads the full theme
 * registry. Client code must not use it: doing so imports dashboard and
 * development config as a side effect. The root-first contract has one
 * project config, so expose just that project's app overrides in a separate
 * generated module. It deliberately has no dependency on theme-registry.ts.
 */
export function generateAppConfigClient(themes, config) {
  const outputFilePath = join(config.outputDir, 'app-config.client.ts')
  const project = themes.find(theme => theme.hasAppConfig)
  const appImport = project
    ? `import { ${project.appConfigExportName || 'APP_CONFIG_OVERRIDES'} as projectAppConfigOverrides } from '${project.appConfigPath}'`
    : ''
  const appConfigType = project
    ? `import type { AppConfig } from '${convertCorePath('@/core/lib/config/types', outputFilePath, config)}'`
    : 'type AppConfig = Record<string, never>'
  const value = project ? 'projectAppConfigOverrides' : '{}'

  return `/**
 * Client-Safe Application Config
 *
 * Generated from the root project's app.config.ts only. It intentionally
 * excludes the full theme registry, dashboard.config.ts and dev.config.ts.
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

${appImport}
${appConfigType}

export const APP_CONFIG_OVERRIDES = ${value} as unknown as Partial<AppConfig>
`
}

/**
 * Generate the public dashboard-config input used by client dashboard UI.
 * Dashboard config used to be reached through config-sync -> theme-registry,
 * which also carries dev.config.ts. Keep the two generated inputs separate so
 * dashboard clients never need the server registry.
 */
export function generateDashboardConfigClient(themes, config) {
  const outputFilePath = join(config.outputDir, 'dashboard-config.client.ts')
  const project = themes.find(theme => theme.hasDashboardConfig)
  const dashboardImport = project
    ? `import { ${project.dashboardConfigExportName || 'DASHBOARD_CONFIG'} as projectDashboardConfig } from '${project.dashboardConfigPath}'`
    : ''
  const dashboardConfigType = project
    ? `import type { DashboardConfig } from '${convertCorePath('@/core/lib/config/dashboard.config', outputFilePath, config)}'`
    : 'type DashboardConfig = Record<string, never>'
  const value = project ? 'projectDashboardConfig' : '{}'

  return `/**
 * Client-Safe Dashboard Config
 *
 * Generated from the root project's dashboard.config.ts only. It deliberately
 * excludes theme-registry.ts, app config and dev.config.ts.
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

${dashboardImport}
${dashboardConfigType}

export const DASHBOARD_CONFIG_OVERRIDES = ${value} as unknown as Partial<DashboardConfig>
`
}

/**
 * Generate the development-only DevKeyring input used by LoginForm.
 *
 * The config holds test credentials, so it cannot be statically imported by a
 * module that reaches production client bundles. Webpack replaces NODE_ENV
 * while compiling production builds and does not traverse the unreachable
 * require below; development builds retain the synchronous import and keep
 * the existing immediately-rendered login experience.
 */
export function generateDevKeyringClient(themes, config) {
  const outputFilePath = join(config.outputDir, 'dev-keyring.client.ts')
  const project = themes.find(theme => theme.hasDevConfig)
  const devConfigType = project
    ? `import type { DevConfig } from '${convertCorePath('@/core/lib/config/types', outputFilePath, config)}'`
    : 'type DevConfig = { devKeyring?: never }'
  const loadDevConfig = project
    ? `require('${project.devConfigPath}').${project.devConfigExportName || 'DEV_CONFIG_OVERRIDES'} as DevConfig`
    : 'undefined'

  return `/**
 * Development-only DevKeyring config.
 *
 * This file is safe for LoginForm to import: the project dev.config.ts is
 * required only outside production, so its test credentials are absent from
 * production browser bundles.
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

${devConfigType}

const DEV_CONFIG: DevConfig | undefined =
  process.env.NODE_ENV !== 'production' ? ${loadDevConfig} : undefined

export const DEV_KEYRING_CONFIG = DEV_CONFIG?.devKeyring
`
}
