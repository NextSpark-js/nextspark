/**
 * Request Locale Generator
 *
 * Generates request-locale.ts from `i18n.requestLocale` of the project's app.config.ts.
 *
 * With Cache Components the `(auth)` and `(public)` groups provide the default locale's messages, fixed when the
 * app is built, so their pages are prerendered. `i18n.requestLocale: { auth, public }` turns one group (or both) to the
 * request's locale. The choice is made here, as a literal, so a bundler drops the branch that is not taken: a project
 * that leaves the setting off ships and prerenders exactly what it did before. The value is read from the file as text,
 * as `providers.scope` is (see ./root-providers.mjs).
 *
 * @module core/scripts/build/registry/generators/request-locale
 */

import { existsSync, readFileSync } from 'fs'
import { join } from 'path'

const GROUPS = ['auth', 'public']

/** The source with its comments blanked (same offsets) and the ranges of its strings: a match inside one is text. */
function scan(source) {
  const strings = []
  const code = source.replace(/("(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'|`(?:\\.|[^`\\])*`)|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, (match, string, offset) => {
    if (string) {
      strings.push([offset, offset + match.length])
      return match
    }
    return match.replace(/[^\n]/g, ' ')
  })
  return { code, inString: index => strings.some(([start, end]) => index > start && index < end) }
}

/**
 * `i18n.requestLocale` of the project's config/app.config.ts: `{ auth, public }`, both false without the file or the setting.
 * Only the literal form `requestLocale: { auth: true, public: false }` is read, inside the `i18n: { … }` block (a
 * `requestLocale` elsewhere in the file does not count; `true as const` is accepted). A variable (`requestLocale: shared`)
 * is not read and gives false (development warns when the merged config says otherwise). Inside the braces, a value that
 * is not the literal `true` or `false`, a key that is not `auth` or `public`, a quoted key and a spread stop the generation
 * with an error. The `i18n` block is found by its first `i18n: {` and brace matching, so a nested `i18n` key is not told apart.
 *
 * @param {string} projectRoot
 * @returns {{ auth: boolean, public: boolean }}
 */
export function readRequestLocale(projectRoot) {
  const result = { auth: false, public: false }
  const appConfigPath = join(projectRoot, 'config', 'app.config.ts')
  if (!existsSync(appConfigPath)) return result
  const { code, inString } = scan(readFileSync(appConfigPath, 'utf8'))
  const open = [...code.matchAll(/\bi18n\s*:\s*\{/g)].find(found => !inString(found.index))
  if (!open) return result
  let depth = 0
  let end = code.length
  for (let i = open.index + open[0].length - 1; i < code.length; i++) {
    if (inString(i)) continue
    if (code[i] === '{') depth++
    else if (code[i] === '}' && --depth === 0) { end = i; break }
  }
  const block = code.slice(open.index, end)
  const match = [...block.matchAll(/\brequestLocale\s*:\s*\{([^{}]*)\}/g)].find(found => !inString(open.index + found.index))
  if (!match) return result
  for (const entry of match[1].split(',').map(part => part.trim()).filter(Boolean)) {
    const pair = entry.match(/^(\w+)\s*:\s*(.+)$/)
    const key = pair?.[1]
    if (!key || !GROUPS.includes(key)) {
      throw new Error(`i18n.requestLocale in config/app.config.ts has ${key ? `an unknown group "${key}"` : `an entry it cannot read ("${entry}")`} (expected ${GROUPS.join(' and ')}): it is read when the registries are generated`)
    }
    const value = pair[2].trim().replace(/\s+as\s+const$/, '')
    if (value !== 'true' && value !== 'false') {
      throw new Error(`i18n.requestLocale.${key} in config/app.config.ts must be the literal true or false (found ${value}): it is read when the registries are generated`)
    }
    result[key] = value === 'true'
  }
  return result
}

/**
 * request-locale.ts: the two groups' settings as constants, and whether the public pages are in the default locale.
 * `PUBLIC_IN_DEFAULT_LOCALE` is true for a Cache Components host whose `(public)` group keeps the default locale: the
 * server components of those pages ask for that locale too, so they agree with the layout's navbar and footer.
 */
export function generateRequestLocale(flags, ppr) {
  return `/**
 * Request Locale
 *
 * \`i18n.requestLocale\` of the project's app.config.ts, read when the registries are generated.
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

export const REQUEST_LOCALE_AUTH: boolean = ${flags.auth}
export const REQUEST_LOCALE_PUBLIC: boolean = ${flags.public}
export const PUBLIC_IN_DEFAULT_LOCALE: boolean = ${Boolean(ppr) && !flags.public}
`
}
