/**
 * Icon Registry Generator
 *
 * Generates icon-registry.ts: a name -> component map holding only the
 * lucide-react icons the app can look up by string.
 *
 * Named imports are what makes this work. `import * as Icons from
 * 'lucide-react'` forces the bundler to keep the whole icon set — ~500 KB
 * that ships to every route, including public ones that render none of it —
 * because it can't prove which members are used. The set of names is known
 * at build time (see discovery/icons.mjs), so it is spelled out here.
 *
 * @module core/scripts/build/registry/generators/icon-registry
 */

/**
 * Generate the icon registry file
 * @param {string[]} iconNames - Icon names discovered by discoverIcons()
 * @param {object} config - Configuration object from getConfig()
 * @returns {string} Generated TypeScript content
 */
export function generateIconRegistry(iconNames, config) {
  const names = [...new Set(iconNames)].sort()
  const importList = names.map(name => `  ${name}`).join(',\n')
  const entryList = names.map(name => `  ${name}`).join(',\n')

  return `/**
 * Auto-generated Icon Registry
 *
 * Generated at: ${new Date().toISOString()}
 * Icons referenced by name: ${names.length}
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

import type { LucideIcon } from 'lucide-react'
import {
${importList}
} from 'lucide-react'

/**
 * Every icon the app can resolve from a configured string name.
 * Anything outside this map falls back to the caller's default icon.
 */
export const ICON_REGISTRY: Record<string, LucideIcon> = {
${entryList}
}

export type IconName = keyof typeof ICON_REGISTRY

export const ICON_METADATA = {
  totalIcons: ${names.length},
  generatedAt: '${new Date().toISOString()}'
}
`
}
