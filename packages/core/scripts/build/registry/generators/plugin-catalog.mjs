/**
 * Plugin Catalog Generator
 *
 * Generates plugin-catalog.ts: static metadata (name, version, capabilities, what a plugin contributes) of
 * EVERY enabled plugin, whatever it declares. plugin-registry.ts holds only the plugins that declare
 * 'server' and plugin-registry.client.ts only the ones that declare 'web', because those files import the
 * plugin's code; a catalog or listing (API, devtools) reads this file instead, which imports nothing.
 *
 * @module core/scripts/build/registry/generators/plugin-catalog
 */

import { capabilitiesOf } from '../discovery/plugin-capabilities.mjs'

const literal = value => JSON.stringify(value)

/**
 * @param {Array} plugins - every discovered plugin (not filtered by capability)
 * `enabled` is the config's literal boolean, or null (unknown: computed at run time); it is never assumed true.
 * @returns {string} Generated TypeScript content
 */
export function generatePluginCatalog(plugins) {
  const sorted = [...plugins].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
  const entries = sorted.map(plugin => {
    const metadata = plugin.metadata ?? {}
    const fields = [
      ['name', plugin.name],
      ['displayName', metadata.displayName ?? plugin.name],
      ['version', metadata.version ?? null],
      ['description', metadata.description ?? null],
      ['enabled', metadata.enabled ?? null],
      ['capabilities', capabilitiesOf(plugin)],
      ['hasAPI', Boolean(plugin.hasAPI)],
      ['apiPath', plugin.apiPath ?? null],
      ['entities', (plugin.entities ?? []).map(entity => entity.name)],
      ['hasMessages', Boolean(plugin.hasMessages)],
      ['hasAssets', Boolean(plugin.hasAssets)],
    ]
    return `  ${literal(plugin.name)}: {\n${fields.map(([key, value]) => `    ${key}: ${literal(value)}`).join(',\n')}\n  }`
  })
  return `/**
 * Auto-generated Plugin Catalog - CAPABILITY-NEUTRAL
 *
 * Plugins discovered: ${plugins.length}
 *
 * Static metadata of every enabled plugin, including the ones that declare neither 'server' nor 'web'.
 * Imports nothing, so server and client code can read it. For a plugin's config and code use
 * plugin-registry (the 'server' plugins) or plugin-registry.client (the 'web' plugins).
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

export type PluginCatalogCapability = 'server' | 'web' | 'build' | 'mobile'

export interface PluginCatalogEntry {
  name: string
  displayName: string
  version: string | null
  description: string | null
  /** The config literal enabled flag; null when it is computed at run time (unknown) */
  enabled: boolean | null
  capabilities: PluginCatalogCapability[]
  hasAPI: boolean
  apiPath: string | null
  entities: string[]
  hasMessages: boolean
  hasAssets: boolean
}

export const PLUGIN_CATALOG: Record<string, PluginCatalogEntry> = {
${entries.join(',\n')}
}
`
}
