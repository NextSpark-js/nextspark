/**
 * Features Generator
 *
 * Generates features.ts from the `features` of the project's nextspark.config.ts (#425): the flags the generated host
 * was built with, which core's UI reads (src/lib/config/build-features.ts) so it links to no page a flag turned off
 * left out (host/features.mjs).
 *
 * @module core/scripts/build/registry/generators/features
 */

/** The flags that are read, and their default. */
const DEFAULT_FEATURES = { billing: true }

/**
 * @param {Record<string, boolean>|undefined} features - the resolved `features` of nextspark.config.ts
 * @returns {string}
 */
export function generateFeatures(features = {}) {
  const flags = Object.fromEntries(Object.entries(DEFAULT_FEATURES).map(([flag, fallback]) => [flag, features[flag] ?? fallback]))
  return `/**
 * Features
 *
 * \`features\` of the project's nextspark.config.ts, read when the registries are generated.
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

export const FEATURES: { readonly ${Object.keys(flags).map(flag => `${flag}: boolean`).join('; ')} } = ${JSON.stringify(flags)}
`
}
