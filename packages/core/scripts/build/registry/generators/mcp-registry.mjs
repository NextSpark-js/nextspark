/**
 * MCP Override Registry Generator
 *
 * Generates mcp-registry.ts: a literal-import map of discovered
 * `entities/<slug>/mcp.ts` files (see discovery/mcp-overrides.mjs), consumed
 * by the default `/api/mcp` route template to build the `overrides` option
 * passed to `createMcpEngine`. Follows entity-registry.mjs's literal-import
 * pattern (not the regex-parsing approach used for api-presets.ts) because
 * an McpEntityOverride exports real functions — transformInput, extraTools —
 * that can't be recovered from source text.
 *
 * @module core/scripts/build/registry/generators/mcp-registry
 */

import { join } from 'path'
import { convertCorePath } from '../config.mjs'

/**
 * Generate the MCP override registry file.
 * @param {Array<{slug: string, importPath: string, themeName: string}>} mcpOverrides - Discovered overrides
 * @param {object} config - Configuration object from getConfig()
 * @returns {string} Generated TypeScript content
 */
export function generateMcpRegistry(mcpOverrides, config) {
  const outputFilePath = join(config.outputDir, 'mcp-registry.ts')

  const importName = (slug) => `${toPascalCase(slug)}McpOverride`

  const imports = mcpOverrides
    .map((entry) => `import ${importName(entry.slug)} from '${entry.importPath}'`)
    .join('\n')

  const entries = mcpOverrides
    .map((entry) => `  '${entry.slug}': ${importName(entry.slug)},`)
    .join('\n')

  return `/**
 * Auto-generated MCP Override Registry
 *
 * Generated at: ${new Date().toISOString()}
 * MCP overrides discovered: ${mcpOverrides.length}
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build/registry.mjs
 */

${imports}
import type { McpEntityOverride } from '${convertCorePath('@/core/lib/mcp', outputFilePath, config)}'

export const MCP_OVERRIDES: Record<string, McpEntityOverride> = {
${entries}
}
`
}

function toPascalCase(slug) {
  return slug
    .split(/[-_/]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}
