/**
 * Root Providers Generator
 *
 * Generates providers-scope.ts and root-providers.ts from `providers.scope` of the project's app.config.ts.
 *
 * The root layout mounts React Query and the toaster for every route by default. A client component a server layout
 * imports is in the entry chunks of every route whether or not it renders it, and a condition read from the merged
 * config at runtime does not stop the bundler from keeping the import. So with `providers.scope: 'groups'` the generated
 * `root-providers.ts` exports nothing to mount, and a public page ships neither library. The value is read from the
 * file as text, as the translation registry does for defaultLocale.
 *
 * @module core/scripts/build/registry/generators/root-providers
 */

import { existsSync, readFileSync } from 'fs'
import { join } from 'path'
import { convertCorePath } from '../config.mjs'

/** The source without comments; the strings stay as they are, so a URL's `//` is not taken for one. */
function stripComments(source) {
  return source.replace(/("(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'|`(?:\\.|[^`\\])*`)|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, (_, string) => string ?? '')
}

/**
 * `providers.scope` of the project's config/app.config.ts: 'root' (the default, also without the file) or 'groups'.
 * Anything else is an error rather than a silent 'root': the setting cannot be read from an expression.
 *
 * @param {string} projectRoot
 * @returns {'root' | 'groups'}
 */
export function readProvidersScope(projectRoot) {
  const appConfigPath = join(projectRoot, 'config', 'app.config.ts')
  if (!existsSync(appConfigPath)) return 'root'
  const source = stripComments(readFileSync(appConfigPath, 'utf8'))
  const match = source.match(/\bproviders\s*:\s*\{[^{}]*?\bscope\s*:\s*([^,}\n]+)/)
  if (!match) return 'root'
  const value = match[1].trim()
  const literal = value.match(/^(['"])(root|groups)\1(?:\s+as\s+const)?$/)
  if (!literal) throw new Error(`providers.scope in config/app.config.ts must be the literal 'root' or 'groups' (found ${value}): it is read when the registries are generated`)
  return literal[2]
}

/** providers-scope.ts: the setting as a constant, which public-config-client turns into ROOT_PROVIDERS. */
export function generateProvidersScope(scope) {
  return `/**
 * Providers Scope
 *
 * \`providers.scope\` of the project's app.config.ts, read when the registries are generated.
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

export const PROVIDERS_SCOPE: 'root' | 'groups' = '${scope}'
`
}

/**
 * root-providers.ts: what the root layout mounts for every route. With scope 'root' the React Query provider and the
 * toaster; with 'groups' nothing (null), and no import of either, so no route that does not mount them ships them.
 */
export function generateRootProviders(scope, config) {
  const body = scope === 'groups'
    ? `export const RootQueryProvider = null
export const RootToaster = null
`
    : `export { QueryProvider as RootQueryProvider } from '${convertCorePath('@/core/providers/query-provider', null, config)}'
export { Toaster as RootToaster } from '${convertCorePath('@/core/components/ui/sonner', null, config)}'
`
  return `/**
 * Root Providers
 *
 * The app-wide providers the root layout mounts (providers.scope '${scope}').
 *
 * DO NOT EDIT - This file is auto-generated by scripts/build-registry.mjs
 */

${body}`
}
