/**
 * A throwaway generated host for the prepare tests: a synthetic project source (`source/`) and a
 * host directory (`host/`) under one temporary root, generated through the production pipeline
 * with the conformance fixture's fake core. TypeScript and Next.js resolve from packages/core.
 */
import { createHash } from 'node:crypto'
import { lstatSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, readlinkSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'

import { hashInputs } from '../generation.mjs'
import { CORE_ROOT, FAKE_CORE_ROOT, MODES, PAGE_EXTENSIONS, loadFixtureCoreRoutes } from '../../../../../tests/fixtures/host-conformance/plan.mjs'

export { CORE_ROOT }

export const PAGE = name => `export default function ${name}() { return null }\n`
export const ROUTE = 'export async function GET() { return Response.json({ ok: true }) }\n'
export const REGISTRY = "export const EXAMPLE_REGISTRY = { answer: 42 } as const\n"

export function write(root, path, content) {
  mkdirSync(dirname(join(root, path)), { recursive: true })
  writeFileSync(join(root, path), content)
}

/** The host config of a temporary root (`source/` project, `host/` host), for tests and their child processes. */
export function hostConfig(root, overrides = {}) {
  const source = join(root, 'source')
  const hostRoot = join(root, 'host')
  return {
    hostRoot,
    projectRoot: CORE_ROOT,
    coreRoot: FAKE_CORE_ROOT,
    loadCoreRoutes: loadFixtureCoreRoutes,
    plugins: [],
    project: { root: source, importBase: '@', label: '.' },
    modes: MODES,
    pageExtensions: PAGE_EXTENSIONS,
    registries: async () => [{ path: '.nextspark/registries/example.ts', content: REGISTRY, grammar: 'registry' }],
    inputs: () => hashInputs({ root: source, dirs: ['templates', 'api'] }),
    versions: { next: 'test' },
    watch: { dirs: [join(source, 'templates'), join(source, 'api')], files: [] },
    ...overrides,
  }
}

/** A registry producer of `count` numbered registries whose content is tagged `tag`. */
export function manyRegistries(count, tag) {
  return async () =>
    Array.from({ length: count }, (_, index) => ({
      path: `.nextspark/registries/r${String(index).padStart(5, '0')}.ts`,
      content: `// Generated by NextSpark (${tag})\nexport const R${index} = { tag: '${tag}' } as const\n`,
      grammar: 'registry',
    }))
}

/** A temporary project source with `files` (paths under source/), and its host config. */
export function tempHost(files = {}, overrides = {}) {
  const root = mkdtempSync(join(tmpdir(), 'nextspark-host-'))
  const source = join(root, 'source')
  const hostRoot = join(root, 'host')
  mkdirSync(hostRoot, { recursive: true })
  for (const [path, content] of Object.entries(files)) write(source, path, content)
  const config = hostConfig(root, overrides)
  return { root, source, hostRoot, config, cleanup: () => rmSync(root, { recursive: true, force: true }) }
}

/** Every entry under `root`: files by content hash and mtime, symlinks by target, directories by name. */
export function snapshot(root, { mtimes = true } = {}) {
  const entries = {}
  const walk = relative => {
    for (const entry of readdirSync(join(root, relative), { withFileTypes: true })) {
      const path = relative ? `${relative}/${entry.name}` : entry.name
      const stat = lstatSync(join(root, path))
      if (stat.isSymbolicLink()) entries[path] = `-> ${readlinkSync(join(root, path))}`
      else if (stat.isDirectory()) {
        entries[path] = 'dir'
        walk(path)
      } else {
        const hash = createHash('sha256').update(readFileSync(join(root, path))).digest('hex').slice(0, 16)
        entries[path] = mtimes ? `${hash}@${stat.mtimeMs}` : hash
      }
    }
  }
  walk('')
  return entries
}

export const read = (root, path) => readFileSync(join(root, path), 'utf8')
