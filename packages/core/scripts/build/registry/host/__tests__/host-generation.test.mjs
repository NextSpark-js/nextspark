test('nothing is written through a symlink in src/app, the registries or on the way to them', async () => {
  for (const [label, arrange, expected] of [
    ['a route directory linked outside', (host, outside) => {
      rmSync(join(host.hostRoot, 'src/app/about'), { recursive: true })
      symlinkSync(outside, join(host.hostRoot, 'src/app/about'))
    }, 'src/app/about is a symlink'],
    ['src/app linked outside', (host, outside) => {
      rmSync(join(host.hostRoot, 'src/app'), { recursive: true })
      symlinkSync(outside, join(host.hostRoot, 'src/app'))
    }, 'src/app is a symlink'],
    ['a registry linked to a file outside', (host, outside) => {
      write(outside, 'target.ts', '// outside\n')
      unlinkSync(join(host.hostRoot, '.nextspark/registries/example.ts'))
      symlinkSync(join(outside, 'target.ts'), join(host.hostRoot, '.nextspark/registries/example.ts'))
    }, '.nextspark/registries/example.ts is a symlink'],
  ]) {
    const host = tempHost(SOURCE)
    const outside = mkdtempSync(join(tmpdir(), 'nextspark-host-outside-'))
    try {
      await prepareHost(host.config)
      arrange(host, outside)
      write(host.source, 'templates/about/page.tsx', PAGE('AboutChanged'))
      write(host.source, 'templates/new/page.tsx', PAGE('New'))
      const outsideBefore = snapshot(outside)
      const recordBefore = read(host.hostRoot, GENERATION_FILE)
      await assert.rejects(prepareHost(host.config), error => {
        assert.ok(error instanceof PrepareError, label)
        assert.ok(codes(error).includes(GENERATION_DIAGNOSTICS.SYMLINK), `${label}: ${error.message}`)
        assert.ok(error.message.includes(expected), `${label}: ${error.message}`)
        return true
      })
      assert.deepEqual(snapshot(outside), outsideBefore, `${label}: nothing changed outside`)
      assert.equal(read(host.hostRoot, GENERATION_FILE), recordBefore, `${label}: record unchanged`)
    } finally {
      host.cleanup()
      rmSync(outside, { recursive: true, force: true })
    }
  }
})

test('a failed generation leaves the previous one intact and names the source', async () => {
  const host = tempHost(SOURCE)
  try {
    await prepareHost(host.config)
    const before = snapshot(host.hostRoot)
    write(host.source, 'templates/about/page.tsx', 'export default function About() { return null }\nexport const helper = 1\n')
    write(host.source, 'templates/broken/page.tsx', 'export default function (\n')
    await assert.rejects(prepareHost(host.config), error => {
      assert.ok(error instanceof PrepareError)
      assert.deepEqual(codes(error).sort(), ['NS_HOST_PARSE_ERROR', 'NS_HOST_UNSUPPORTED_EXPORT'])
      assert.match(error.message, /templates\/about\/page\.tsx:2: \(export "helper"\)/)
      assert.match(error.message, /templates\/broken\/page\.tsx/)
      return true
    })
    assert.deepEqual(snapshot(host.hostRoot), before)
  } finally {
    host.cleanup()
  }
})

test('a collision or a registry outside its grammar fails before anything is written', async () => {
  const host = tempHost({ ...SOURCE, 'templates/api/notes/route.ts': ROUTE })
  try {
    await assert.rejects(prepareHost(host.config), error => {
      assert.deepEqual(codes(error), ['NS_HOST_ROUTE_COLLISION'])
      assert.match(error.message, /api\/notes\/route\.ts and templates\/api\/notes\/route\.ts/)
      return true
    })
    assert.equal(existsSync(join(host.hostRoot, 'src')), false)

    unlinkSync(join(host.source, 'templates/api/notes/route.ts'))
    const lookup = { ...host.config, registries: async () => [{ path: '.nextspark/registries/bad.ts', content: "import * as all from './x'\nexport const R = { page: all[process.env.KEY] }\n", grammar: 'registry' }] }
    await assert.rejects(prepareHost(lookup), error => {
      assert.ok(codes(error).every(code => code === GENERATION_DIAGNOSTICS.GRAMMAR))
      return true
    })
    const escape = { ...host.config, registries: async () => [{ path: '../outside.ts', content: REGISTRY, grammar: null }] }
    await assert.rejects(prepareHost(escape), error => codes(error).includes(GENERATION_DIAGNOSTICS.UNSAFE_PATH))
    assert.equal(existsSync(join(host.hostRoot, 'src')), false)
  } finally {
    host.cleanup()
  }
})

test('one writer at a time: a live lock refuses, a stale one is recovered', async () => {
  const host = tempHost(SOURCE)
  try {
    const release = acquireLock(host.hostRoot)
    await assert.rejects(prepareHost(host.config), error => {
      assert.deepEqual(codes(error), [GENERATION_DIAGNOSTICS.LOCKED])
      assert.match(error.message, new RegExp(`pid ${process.pid}`))
      return true
    })
    release()
    assert.equal(existsSync(join(host.hostRoot, LOCK_FILE)), false)

    // A dead writer on this machine
    const dead = spawnSync(process.execPath, ['-e', 'process.stdout.write(String(process.pid))'], { encoding: 'utf8' })
    write(host.hostRoot, LOCK_FILE, JSON.stringify({ pid: Number(dead.stdout), host: hostname(), startedAt: new Date().toISOString(), token: 'x' }))
    assert.match(staleLockReason(join(host.hostRoot, LOCK_FILE)), /process \d+ is gone/)
    await prepareHost(host.config)

    // An old lock, whoever held it
    write(host.hostRoot, LOCK_FILE, JSON.stringify({ pid: 1, host: 'elsewhere', startedAt: new Date(Date.now() - 60 * 60 * 1000).toISOString(), token: 'y' }))
    assert.match(staleLockReason(join(host.hostRoot, LOCK_FILE)), /older than/)
    await prepareHost(host.config)

    // An unreadable lock only once it is clearly abandoned
    write(host.hostRoot, LOCK_FILE, '')
    assert.equal(staleLockReason(join(host.hostRoot, LOCK_FILE)), null)
    const old = new Date(Date.now() - 60_000)
    utimesSync(join(host.hostRoot, LOCK_FILE), old, old)
    assert.match(staleLockReason(join(host.hostRoot, LOCK_FILE)), /unreadable/)
    await prepareHost(host.config)
    assert.equal(existsSync(join(host.hostRoot, LOCK_FILE)), false)

    // A release never removes a lock another writer took over
    const mine = acquireLock(host.hostRoot)
    write(host.hostRoot, LOCK_FILE, JSON.stringify({ pid: process.pid, host: hostname(), startedAt: new Date().toISOString(), token: 'someone-else' }))
    mine()
    assert.equal(existsSync(join(host.hostRoot, LOCK_FILE)), true)
  } finally {
    host.cleanup()
  }
})

test('--check: not prepared, up to date, then each way a host goes stale, missing or foreign', async () => {
  const host = tempHost(SOURCE)
  const states = async () => (await checkHost(host.config)).problems.map(problem => `${problem.state} ${problem.path ?? ''}`.trim())
  try {
    const clean = await checkHost(host.config)
    assert.equal(clean.ok, false)
    assert.deepEqual(clean.problems.map(problem => problem.state), ['not-prepared'])
    assert.match(clean.problems[0].detail, /run nextspark prepare/)

    await prepareHost(host.config)
    assert.deepEqual(await checkHost(host.config), { ok: true, problems: [] })

    unlinkSync(join(host.hostRoot, 'src/app/about/page.tsx'))
    write(host.hostRoot, 'src/app/page.tsx', '// edited by hand\n')
    write(host.hostRoot, 'src/app/extra/page.tsx', PAGE('Extra'))
    write(host.hostRoot, '.nextspark/registries/example.ts', '// edited\n')
    // A generated file edited by hand is no longer NextSpark's: foreign, and prepare refuses rather than overwrite it
    assert.deepEqual(await states(), ['missing src/app/about/page.tsx', 'foreign src/app/page.tsx', 'foreign src/app/extra/page.tsx', 'stale .nextspark/registries/example.ts'])
    await assert.rejects(prepareHost(host.config), error => {
      assert.deepEqual(error.diagnostics[0].files, ['src/app/extra/page.tsx', 'src/app/page.tsx'])
      return true
    })
    assert.equal(read(host.hostRoot, 'src/app/page.tsx'), '// edited by hand\n')

    rmSync(join(host.hostRoot, 'src/app/extra'), { recursive: true })
    unlinkSync(join(host.hostRoot, 'src/app/page.tsx'))
    await prepareHost(host.config)
    assert.deepEqual(await states(), [])

    // A source edit that leaves every facade as it is still makes the registries' inputs stale
    write(host.source, 'templates/about/page.tsx', `// a comment\n${PAGE('About')}`)
    write(host.source, 'templates/new/page.tsx', PAGE('New'))
    assert.deepEqual(await states(), ['missing src/app/new/page.tsx', 'stale templates/about/page.tsx', 'stale templates/new/page.tsx'])
    await prepareHost(host.config)
    assert.deepEqual(await states(), [])

    // Another Next.js (or core, cli) than the one that generated it
    assert.deepEqual((await checkHost({ ...host.config, versions: { next: 'other' } })).problems.map(p => p.detail), ['generated with next test, now other'])

    // A broken source: check reports what prepare would fail with
    write(host.source, 'templates/about/page.tsx', 'export const revalidate = Number(60)\nexport default function A() { return null }\n')
    const invalid = await checkHost(host.config)
    assert.equal(invalid.ok, false)
    assert.deepEqual(invalid.problems.map(p => p.state), ['invalid'])
    assert.match(invalid.problems[0].detail, /NS_HOST_NON_LITERAL_SEGMENT_CONFIG/)
  } finally {
    host.cleanup()
  }
})

test('an interrupted publication is visible to --check and completed by the next prepare', async () => {
  const host = tempHost(SOURCE)
  try {
    await prepareHost(host.config)
    const record = JSON.parse(read(host.hostRoot, GENERATION_FILE))
    const half = '// written before the interruption\n'
    write(host.hostRoot, GENERATION_FILE, JSON.stringify({ ...record, pending: true, files: { ...record.files, 'src/app/half/page.tsx': createHash('sha256').update(half).digest('hex') } }))
    write(host.hostRoot, 'src/app/half/page.tsx', half)
    const checked = await checkHost(host.config)
    assert.deepEqual(checked.problems.map(p => `${p.state} ${p.path}`), [`stale ${GENERATION_FILE}`, 'stale src/app/half/page.tsx'])
    const result = await prepareHost(host.config)
    assert.deepEqual(result.deleted, ['src/app/half/page.tsx'], 'what an interrupted run wrote is owned, so it is cleaned up')
    assert.deepEqual(await checkHost(host.config), { ok: true, problems: [] })
  } finally {
    host.cleanup()
  }
})

test('a dev generation composes the root layout with the status reporter; production has none of it', async () => {
  const host = tempHost(SOURCE)
  try {
    await prepareHost(host.config, { devStatus: true })
    const layout = read(host.hostRoot, 'src/app/layout.tsx')
    assert.match(layout, /\nimport NextSparkSourceLayout from "@fixture-core\/app\/layout"\nimport \{ withGenerationStatus \} from '\.\/_nextspark\/generation-status'\nexport default withGenerationStatus\(NextSparkSourceLayout\)\n/)
    assert.match(layout, /export \{ metadata \} from "@fixture-core\/app\/layout"/, 'other exports still forwarded')
    assert.equal(read(host.hostRoot, DEV_DIAGNOSTIC_FILE).endsWith('export const generationDiagnostic = ""\n'), true)
    for (const [path, content] of Object.entries(DEV_RUNTIME_FILES)) assert.equal(read(host.hostRoot, path), content)
    assert.match(read(host.hostRoot, DEV_REPORTER_FILE), /^'use client'\n/)
    assert.deepEqual(await checkHost(host.config, { dev: true }), { ok: true, problems: [] }, 'a dev generation is fresh for --check --dev')

    const production = await prepareHost(host.config, { mode: 'production' })
    assert.deepEqual(production.deleted, [DEV_DIAGNOSTIC_FILE, DEV_REPORTER_FILE, DEV_STATUS_FILE].sort())
    assert.equal(read(host.hostRoot, 'src/app/layout.tsx').includes('_nextspark'), false)
    assert.equal(existsSync(join(host.hostRoot, 'src/app/_nextspark')), false)
  } finally {
    host.cleanup()
  }
})

