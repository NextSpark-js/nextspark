const SOURCE = {
  'templates/about/page.tsx': PAGE('About'),
  'templates/counter/page.tsx': "'use client'\nexport default function Counter() { return null }\n",
  'api/notes/route.ts': ROUTE,
}

const codes = error => error.diagnostics.map(d => d.code)

test('prepare publishes every facade and registry with a deterministic generation record', async () => {
  const one = tempHost(SOURCE)
  const two = tempHost(SOURCE)
  try {
    const result = await prepareHost(one.config, { mode: 'production' })
    assert.deepEqual(result.files.map(file => file.path), [
      'src/app/(shell)/layout.tsx',
      'src/app/(shell)/shell/page.tsx',
      'src/app/about/page.tsx',
      'src/app/api/notes/route.ts',
      'src/app/counter/page.tsx',
      'src/app/error.tsx',
      'src/app/global-error.tsx',
      'src/app/layout.tsx',
      'src/app/page.tsx',
      '.nextspark/registries/example.ts',
    ])
    assert.equal(result.written.length, 10)
    assert.equal(read(one.hostRoot, 'src/app/about/page.tsx'), '// Generated by NextSpark from @/templates/about/page. Do not edit: regenerated on every build.\nexport { default } from "@/templates/about/page"\n')
    assert.equal(read(one.hostRoot, 'src/app/layout.tsx').includes('@fixture-core/app/layout'), true)
    assert.equal(read(one.hostRoot, '.nextspark/registries/example.ts'), REGISTRY)

    const record = readGeneration(one.hostRoot)
    assert.equal(record.schemaVersion, 1)
    assert.equal(record.mode, 'production')
    assert.deepEqual(record.versions, { next: 'test' })
    assert.deepEqual(Object.keys(record.files), [...result.files.map(file => file.path)].sort())
    assert.deepEqual(Object.keys(record.inputs.files), ['api/notes/route.ts', 'templates/about/page.tsx', 'templates/counter/page.tsx'])
    assert.equal(record.pending, undefined)

    // Same sources, another host: the same bytes, record included
    await prepareHost(two.config, { mode: 'production' })
    assert.deepEqual(snapshot(two.hostRoot, { mtimes: false }), snapshot(one.hostRoot, { mtimes: false }))

    // Again: nothing is rewritten, so Next has nothing to recompile
    const before = snapshot(one.hostRoot)
    const again = await prepareHost(one.config, { mode: 'production' })
    assert.deepEqual([again.written, again.deleted, again.unchanged], [[], [], 10])
    const after = snapshot(one.hostRoot)
    delete before[GENERATION_FILE]
    delete after[GENERATION_FILE]
    assert.deepEqual(after, before)
    assert.equal(existsSync(join(one.hostRoot, LOCK_FILE)), false, 'the lock is released')
  } finally {
    one.cleanup()
    two.cleanup()
  }
})

test('routes follow the sources: a removed override falls back to core, a removed route is deleted with its empty directory', async () => {
  const host = tempHost(SOURCE)
  try {
    await prepareHost(host.config)
    write(host.hostRoot, '.nextspark/registries/user-note.md', 'not ours\n')
    unlinkSync(join(host.source, 'templates/about/page.tsx'))
    unlinkSync(join(host.source, 'templates/counter/page.tsx'))
    const result = await prepareHost(host.config)
    assert.deepEqual(result.written, ['src/app/about/page.tsx'])
    assert.deepEqual(result.deleted, ['src/app/counter/page.tsx'])
    assert.match(read(host.hostRoot, 'src/app/about/page.tsx'), /@fixture-core\/app\/about\/page/)
    assert.equal(existsSync(join(host.hostRoot, 'src/app/counter')), false)
    assert.equal(read(host.hostRoot, '.nextspark/registries/user-note.md'), 'not ours\n', 'only files of the previous generation are deleted')
  } finally {
    host.cleanup()
  }
})

test('src/app files the previous generation does not own stop prepare before it writes, naming them', async () => {
  const host = tempHost(SOURCE)
  try {
    write(host.hostRoot, 'src/app/layout.tsx', 'export default function Legacy({ children }) { return children }\n')
    write(host.hostRoot, 'src/app/dashboard/page.tsx', PAGE('Dashboard'))
    const before = snapshot(host.hostRoot)
    await assert.rejects(prepareHost(host.config), error => {
      assert.ok(error instanceof PrepareError)
      assert.deepEqual(codes(error), [GENERATION_DIAGNOSTICS.FOREIGN])
      assert.deepEqual(error.diagnostics[0].files, ['src/app/dashboard/page.tsx', 'src/app/layout.tsx'])
      assert.doesNotMatch(error.message, /nextspark migrate/, 'no advice that cannot work yet')
      assert.match(error.message, /nothing was written or deleted/)
      assert.match(error.message, /the previous generation is unchanged/)
      return true
    })
    const after = snapshot(host.hostRoot)
    delete after['.nextspark']
    assert.deepEqual(after, before, 'nothing written')
    assert.equal(existsSync(join(host.hostRoot, GENERATION_FILE)), false)
  } finally {
    host.cleanup()
  }
})

