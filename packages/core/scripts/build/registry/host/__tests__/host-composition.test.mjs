test('billing.webhookExtensions replaces core\'s webhook route with a composed facade over the project module', async () => {
  const w = world({
    'lib/billing/stripe-webhook-extensions.ts': 'export const stripeWebhookExtensions = {}\n',
    'lib/billing/polar-webhook-extensions.tsx': 'export const polarWebhookExtensions = {}\n',
  })
  try {
    w.write('core/billing-webhooks.ts', 'export function createStripeWebhookRoute(e) { return () => e }\nexport function createPolarWebhookRoute(e) { return () => e }\n')
    const resolveFile = () => join(w.root, 'core/billing-webhooks.ts')
    const { routes: hooks, diagnostics } = webhookRoutes({
      webhookExtensions: { stripe: './lib/billing/stripe-webhook-extensions', polar: 'lib/billing/polar-webhook-extensions.tsx' },
      projectRoot: w.source,
      resolveFile,
    })
    assert.deepEqual(diagnostics, [])
    const route = target => ({ kind: 'route', target, specifier: `@nextsparkjs/core/routes/${target.replace(/\.ts$/, '')}`, file: join(w.root, 'core/layout.tsx'), protected: true })
    const planned = planHost({
      coreRoutes: [route('api/v1/billing/webhooks/stripe/route.ts'), route('api/v1/billing/webhooks/polar/route.ts')],
      webhooks: hooks,
      project: { root: w.source },
    })
    assert.deepEqual(planned.diagnostics, [], 'a configured webhook is the framework composing, so core\'s protection does not stop it')
    const result = await render(planned.routes)
    assert.deepEqual(result.diagnostics, [])
    assert.equal(
      contentOf(result, 'api/v1/billing/webhooks/stripe/route.ts'),
      [
        '// Generated by NextSpark for nextspark.config.ts billing.webhookExtensions.stripe (./lib/billing/stripe-webhook-extensions). Do not edit: regenerated on every build.',
        'import { stripeWebhookExtensions } from "@/lib/billing/stripe-webhook-extensions"',
        'import { createStripeWebhookRoute } from "@nextsparkjs/core/routes/_internal/billing-webhooks"',
        'export const POST = createStripeWebhookRoute(stripeWebhookExtensions)',
        '',
      ].join('\n')
    )
    assert.match(contentOf(result, 'api/v1/billing/webhooks/polar/route.ts'), /import \{ polarWebhookExtensions \} from "@\/lib\/billing\/polar-webhook-extensions"/)
    for (const file of result.files) assert.deepEqual(validateGeneratedModule({ ts, source: file.content, file: file.path, grammar: file.grammar }), [], file.path)
  } finally {
    w.cleanup()
  }
})

test('webhook extension settings that cannot be served are diagnostics, and a missing export is named', async () => {
  const w = world({ 'lib/ext.ts': 'export const other = {}\n' })
  try {
    w.write('core/billing-webhooks.ts', 'export function createStripeWebhookRoute(e) { return () => e }\n')
    const resolveFile = () => join(w.root, 'core/billing-webhooks.ts')
    const problems = webhookRoutes({
      webhookExtensions: { stripe: './lib/missing', polar: '../outside/ext', paypal: './lib/ext' },
      projectRoot: w.source,
      resolveFile,
    }).diagnostics
    assert.deepEqual(problems.map(problem => problem.code), [WEBHOOK_DIAGNOSTICS.MISSING, WEBHOOK_DIAGNOSTICS.INVALID, WEBHOOK_DIAGNOSTICS.INVALID])
    assert.match(problems[0].message, /billing\.webhookExtensions\.stripe: no module found at "\.\/lib\/missing"/)
    assert.match(problems[1].message, /must stay inside the project/)
    assert.match(problems[2].message, /"paypal" is not a webhook provider/)
    for (const value of ['', 5, null]) assert.equal(webhookRoutes({ webhookExtensions: { stripe: value }, projectRoot: w.source, resolveFile }).diagnostics.length, 1)

    const { routes } = webhookRoutes({ webhookExtensions: { stripe: './lib/ext' }, projectRoot: w.source, resolveFile })
    const planned = planHost({
      coreRoutes: [{ kind: 'route', target: 'api/v1/billing/webhooks/stripe/route.ts', specifier: '@nextsparkjs/core/routes/x', file: join(w.root, 'core/layout.tsx'), protected: false }],
      webhooks: routes,
      project: { root: w.source },
    })
    const result = await render(planned.routes)
    assert.match(result.diagnostics[0].message, /lib\/ext does not export "stripeWebhookExtensions"/)
  } finally {
    w.cleanup()
  }
})

test('a project route at the webhook\'s path collides with the configured extensions instead of silently winning', () => {
  const w = world({ 'templates/api/v1/billing/webhooks/stripe/route.ts': 'export async function POST() { return new Response() }\n', 'lib/ext.ts': 'export const stripeWebhookExtensions = {}\n' })
  try {
    const { routes } = webhookRoutes({ webhookExtensions: { stripe: './lib/ext' }, projectRoot: w.source, resolveFile: () => join(w.root, 'core/layout.tsx') })
    const { diagnostics } = planHost({
      coreRoutes: [{ kind: 'route', target: 'api/v1/billing/webhooks/stripe/route.ts', specifier: '@nextsparkjs/core/routes/x', file: '/core/x', protected: false }],
      webhooks: routes,
      project: { root: w.source },
    })
    assert.deepEqual(diagnostics.map(d => d.code), [PLAN_DIAGNOSTICS.COLLISION])
    assert.match(diagnostics[0].message, /two project files provide this route/)
  } finally {
    w.cleanup()
  }
})
