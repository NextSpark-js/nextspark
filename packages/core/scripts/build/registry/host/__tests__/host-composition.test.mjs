test('the root layout imports the project stylesheet, composed or not, and the dev status wrapper goes around either', async () => {
  const w = world({ 'templates/layout.tsx': LAYOUT })
  try {
    const compose = w.compose('withRootLayout', 'root-layout')
    const plain = planHost({ coreRoutes: [w.core('layout.tsx', { compose })], project: { root: join(w.root, 'nowhere') } })
    const composed = planHost({ coreRoutes: [w.core('layout.tsx', { compose })], project: { root: w.source } })

    const noCss = await render(plain.routes)
    assert.doesNotMatch(contentOf(noCss, 'layout.tsx'), /globals\.css/, 'no stylesheet configured: none imported')

    const plainCss = await render(plain.routes, { stylesheet: '@/styles/globals.css' })
    assert.equal(contentOf(plainCss, 'layout.tsx').split('\n')[1], 'import "@/styles/globals.css"')
    assert.equal(plainCss.files[0].grammar, 'facade')

    const composedCss = await render(composed.routes, { stylesheet: '@/styles/globals.css' })
    assert.equal(
      contentOf(composedCss, 'layout.tsx'),
      [
        '// Generated by NextSpark from @/templates/layout. Do not edit: regenerated on every build.',
        'import "@/styles/globals.css"',
        'import NextSparkTemplate from "@/templates/layout"',
        'import { withRootLayout } from "@nextsparkjs/core/routes/_internal/root-layout"',
        'export default withRootLayout(NextSparkTemplate)',
        'export { metadata } from "@nextsparkjs/core/routes/layout"',
        '',
      ].join('\n')
    )

    // Only the root layout: a group layout never imports the stylesheet
    const group = planHost({ coreRoutes: [w.core('(public)/layout.tsx'), w.core('layout.tsx')], project: { root: join(w.root, 'nowhere') } })
    assert.doesNotMatch(contentOf(await render(group.routes, { stylesheet: '@/styles/globals.css' }), '(public)/layout.tsx'), /globals\.css/)

    // nextspark dev: the status wrapper goes outermost, and both files pass the dev grammar
    const dev = await render(composed.routes, { stylesheet: '@/styles/globals.css', devStatus: true })
    assert.deepEqual(dev.diagnostics, [])
    const devRoot = dev.files.find(file => file.path === 'src/app/layout.tsx')
    assert.equal(devRoot.grammar, 'dev-facade')
    assert.match(devRoot.content, /export default withGenerationStatus\(withRootLayout\(NextSparkTemplate\)\)/)
    const devPlain = await render(plain.routes, { stylesheet: '@/styles/globals.css', devStatus: true })
    assert.match(devPlain.files.find(file => file.path === 'src/app/layout.tsx').content, /export default withGenerationStatus\(NextSparkSourceLayout\)/)
  } finally {
    w.cleanup()
  }
})

