/**
 * The default rate limit of project and plugin API routes (#226): every method of a Route Handler under `src/app/api/`
 * that a project or plugin provides is composed with core's read or write limit, as the 0.x dispatchers did, unless
 * the method limits itself or the module exports `rateLimit = false`.
 *
 * Run: node --test packages/core/scripts/build/registry/host/__tests__/host-rate-limit.test.mjs
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'

import { RATE_LIMIT_MODULE, coreRouteRateLimit } from '../rate-limit.mjs'
import { resolveCoreRouteFile } from '../core-routes.mjs'
import { renderHost } from '../render.mjs'
import { validateGeneratedModule } from '../static-imports.mjs'
import { loadTypeScriptFor } from '../../shared/typescript-compiler.mjs'

const CORE_ROOT = join(import.meta.dirname, '../../../../..')
const ts = await loadTypeScriptFor(CORE_ROOT)
const RATE_LIMIT = coreRouteRateLimit(specifier => resolveCoreRouteFile(CORE_ROOT, specifier))

/** Render one route module at `target`, from `origin`, with the default rate limit configured unless `rateLimit: null`. */
async function renderOne(source, { target = 'api/intake/route.ts', origin = 'project', rateLimit = RATE_LIMIT } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'nextspark-rate-limit-'))
  try {
    const file = join(root, target)
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, source)
    const route = { kind: 'route', target, mode: null, specifier: `@/${target.replace(/\.ts$/, '')}`, file, origin, source: `./${target}` }
    return await renderHost({ routes: [route], projectRoot: CORE_ROOT, rateLimit: rateLimit ?? undefined })
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
}

const contentOf = result => {
  assert.deepEqual(result.diagnostics, [])
  return result.files[0].content
}

const ALL_METHODS = ['GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'].map(name => `export async function ${name}() { return Response.json({ ok: true }) }\n`).join('')

test('the core module the facades import exists and exports both wrappers', () => {
  assert.equal(RATE_LIMIT.specifier, '@nextsparkjs/core/routes/_internal/route-rate-limit')
  assert.ok(RATE_LIMIT.file, 'resolved to a file in this core')
})

test('a project API route: GET and HEAD read, POST, PUT, PATCH and DELETE write, OPTIONS forwarded untouched', async () => {
  const result = await renderOne(ALL_METHODS)
  const content = contentOf(result)
  assert.equal(result.files[0].grammar, 'composed-facade')
  assert.equal(
    content,
    '// Generated by NextSpark from @/api/intake/route. Do not edit: regenerated on every build.\n' +
      'export { OPTIONS } from "@/api/intake/route"\n' +
      'import { GET as NextSparkGET, HEAD as NextSparkHEAD, POST as NextSparkPOST, PUT as NextSparkPUT, DELETE as NextSparkDELETE, PATCH as NextSparkPATCH } from "@/api/intake/route"\n' +
      `import { withReadRateLimit, withWriteRateLimit } from "${RATE_LIMIT_MODULE}"\n` +
      'export const GET = withReadRateLimit(NextSparkGET)\n' +
      'export const HEAD = withReadRateLimit(NextSparkHEAD)\n' +
      'export const POST = withWriteRateLimit(NextSparkPOST)\n' +
      'export const PUT = withWriteRateLimit(NextSparkPUT)\n' +
      'export const DELETE = withWriteRateLimit(NextSparkDELETE)\n' +
      'export const PATCH = withWriteRateLimit(NextSparkPATCH)\n'
  )
  assert.deepEqual(validateGeneratedModule({ ts, source: content, file: 'route.ts', grammar: 'composed-facade' }), [])
})

test('a plugin API route is limited the same way; segment config is still copied', async () => {
  const content = contentOf(await renderOne(`export async function POST() { return Response.json({}) }\nexport const maxDuration = 30\n`, { target: 'api/plugins/hello/ping/route.ts', origin: 'plugin' }))
  assert.match(content, /^export const POST = withWriteRateLimit\(NextSparkPOST\)$/m)
  assert.match(content, /^export const maxDuration = 30$/m)
})

test('export const rateLimit = false opts the whole route out, and is never forwarded to Next.js', async () => {
  const content = contentOf(await renderOne(`${ALL_METHODS}export const rateLimit = false\n`))
  assert.equal(
    content,
    '// Generated by NextSpark from @/api/intake/route. Do not edit: regenerated on every build.\n' +
      'export { GET, HEAD, OPTIONS, POST, PUT, DELETE, PATCH } from "@/api/intake/route"\n'
  )
})

test('any other rateLimit value is a diagnostic naming the accepted form', async () => {
  for (const value of ['true', "'strict'", 'process.env.X === "1"']) {
    const result = await renderOne(`export async function POST() { return Response.json({}) }\nexport const rateLimit = ${value}\n`)
    assert.deepEqual(result.files, [])
    assert.deepEqual(result.diagnostics.map(diagnostic => diagnostic.code), ['NS_HOST_INVALID_RATE_LIMIT'], value)
    assert.match(result.diagnostics[0].message, /export const rateLimit = false/)
  }
})

test('a method that limits itself is not wrapped again; the others of the module are', async () => {
  const source = [
    "import { withRateLimitTier as limit, withRateLimit } from '@nextsparkjs/core/lib/api/rate-limit'",
    "import { corsPreflight } from '@nextsparkjs/core/lib/api/cors-response'",
    'const getHandler = async () => Response.json({})',
    "export const GET = limit(getHandler, 'strict')",
    'const putHandler = withLogging(withRateLimit(async () => Response.json({})))',
    'export { putHandler as PUT }',
    'export async function POST() { return Response.json({}) }',
    'export const DELETE = withLogging(async () => Response.json({}))',
    'export const OPTIONS = corsPreflight',
    'function withLogging(handler) { return handler }',
  ].join('\n')
  const content = contentOf(await renderOne(source))
  assert.match(content, /^export \{ GET, OPTIONS, PUT \} from "@\/api\/intake\/route"$/m)
  assert.match(content, /^export const POST = withWriteRateLimit\(NextSparkPOST\)$/m)
  assert.match(content, /^export const DELETE = withWriteRateLimit\(NextSparkDELETE\)$/m)
  assert.doesNotMatch(content, /withReadRateLimit/)
})

test('a namespace import of the rate limit module counts as limiting itself', async () => {
  const content = contentOf(await renderOne("import * as rl from '@nextsparkjs/core/lib/api/rate-limit'\nexport const GET = rl.withRateLimitTier(async () => Response.json({}), 'read')\n"))
  assert.equal(content, '// Generated by NextSpark from @/api/intake/route. Do not edit: regenerated on every build.\nexport { GET } from "@/api/intake/route"\n')
})

test('every method limiting itself leaves a plain facade', async () => {
  const content = contentOf(await renderOne("import { withRateLimitTier } from '@nextsparkjs/core/lib/api/rate-limit'\nexport const GET = withRateLimitTier(async () => Response.json({}), 'read')\n"))
  assert.doesNotMatch(content, /RateLimit/)
})

test('not limited by the host: core routes, Route Handlers outside api/, and a host without the rate limit configured', async () => {
  const plain = /^export \{ GET \} from "@\/[^"]+"$/m
  const GET = 'export async function GET() { return Response.json({}) }\n'
  assert.match(contentOf(await renderOne(GET, { origin: 'core' })), plain)
  assert.match(contentOf(await renderOne(GET, { target: 'feed.xml/route.ts' })), plain)
  assert.match(contentOf(await renderOne(GET, { rateLimit: null })), plain)
})

test('rateLimit stays an unsupported export where the host does not limit the route', async () => {
  const result = await renderOne('export async function GET() { return Response.json({}) }\nexport const rateLimit = false\n', { target: 'feed.xml/route.ts' })
  assert.deepEqual(result.diagnostics.map(diagnostic => [diagnostic.code, diagnostic.exportName]), [['NS_HOST_UNSUPPORTED_EXPORT', 'rateLimit']])
})

test('a core without the rate limit module stops the generation instead of serving the routes unlimited', async () => {
  const result = await renderOne('export async function GET() { return Response.json({}) }\n', { rateLimit: { specifier: RATE_LIMIT_MODULE, file: null } })
  assert.deepEqual(result.diagnostics.map(diagnostic => diagnostic.code), ['NS_HOST_CORE_MODULE_MISSING'])
})
