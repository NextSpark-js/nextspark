/**
 * Stage 4 (#203) through a real project and the installed core's route manifest: per-entity routes,
 * composed layouts, the stylesheet, billing webhook extensions and the API namespaces, generated and
 * published by the production pipeline.
 *
 * Run: node --test packages/core/scripts/build/registry/host/__tests__/host-project-composition.test.mjs
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { PrepareError, checkHost, prepareHost, projectHostConfig, renderHostFiles } from '../prepare.mjs'
import { PAGE, ROUTE, read, write } from './host-helpers.mjs'

const TASKS = `import type { EntityConfig } from '@nextsparkjs/core/lib/entities/types'
export const taskEntityConfig: EntityConfig = {
  slug: 'tasks',
  enabled: true,
  names: { singular: 'task', plural: 'Tasks' },
  ui: { dashboard: { showInMenu: true } },
} as EntityConfig
`
const POSTS = `export const postsEntityConfig = {
  slug: 'posts',
  enabled: true,
  access: { public: true, basePath: '/blog' },
  ui: { dashboard: { showInMenu: true }, public: { hasArchivePage: true } },
  builder: { enabled: true },
}
`
const LAYOUT = 'export default function Layout({ children }: { children: React.ReactNode }) { return children }\n'

function project(extra = {}) {
  const root = mkdtempSync(join(tmpdir(), 'nextspark-host-composition-'))
  write(root, 'nextspark.config.ts', "export default { plugins: [], billing: { webhookExtensions: { stripe: './lib/billing/stripe-webhook-extensions' } } }\n")
  write(root, 'package.json', JSON.stringify({ name: 'composition', dependencies: { next: '16.3.8' } }))
  write(root, 'config/theme.config.ts', "export const compositionThemeConfig = { name: 'composition' }\n")
  write(root, 'styles/globals.css', '@import "tailwindcss";\n')
  write(root, 'lib/billing/stripe-webhook-extensions.ts', 'export const stripeWebhookExtensions = {}\n')
  write(root, 'entities/tasks/tasks.config.ts', TASKS)
  write(root, 'entities/posts/posts.config.ts', POSTS)
  write(root, 'templates/layout.tsx', LAYOUT)
  write(root, 'templates/(public)/layout.tsx', LAYOUT)
  write(root, 'templates/(public)/blog/[slug]/page.tsx', PAGE('BlogPost'))
  write(root, 'templates/dashboard/(main)/tasks/page.tsx', PAGE('Tasks'))
  write(root, 'api/ai/usage/route.ts', ROUTE)
  for (const [path, content] of Object.entries(extra)) write(root, path, content)
  return { root, cleanup: () => rmSync(root, { recursive: true, force: true }) }
}

const at = (files, path) => files.find(file => file.path === path)?.content

test('a real project: composed layouts, per-entity routes, the stylesheet, webhook extensions and /api/<path>, published and fresh', { timeout: 180_000 }, async () => {
  const { root, cleanup } = project()
  try {
    const config = projectHostConfig({ projectRoot: root })
    const generated = await prepareHost(config, { mode: 'production' })
    const app = generated.files.filter(file => file.path.startsWith('src/app/'))
    const routes = new Set(app.map(file => file.path.slice('src/app/'.length)))

    // Composed layouts and the stylesheet
    assert.equal(
      read(root, 'src/app/layout.tsx'),
      [
        '// Generated by NextSpark from @/templates/layout. Do not edit: regenerated on every build.',
        'import "@/styles/globals.css"',
        'import NextSparkTemplate from "@/templates/layout"',
        'import { withRootLayout } from "@nextsparkjs/core/routes/_internal/root-layout"',
        'export default withRootLayout(NextSparkTemplate)',
        'export { metadata } from "@nextsparkjs/core/routes/layout"',
        '',
      ].join('\n')
    )
    assert.match(read(root, 'src/app/(public)/layout.tsx'), /export default withPublicMessages\(NextSparkTemplate\)/)
    // Its metadata comes from the composition module, never from core's layout (whose default layout's client
    // components would then ship on every public route, though the override renders none of them)
    assert.match(read(root, 'src/app/(public)/layout.tsx'), /export \{ metadata \} from "@nextsparkjs\/core\/routes\/_internal\/public-layout"/)
    assert.doesNotMatch(read(root, 'src/app/(public)/layout.tsx'), /routes\/\(public\)\/layout/)
    assert.equal(at(app, 'src/app/(auth)/layout.tsx').includes('withAuthMessages'), false, 'no override: core\'s own layout, as it is')

    // One concrete route per entity; the project's task template is composed into the list page
    assert.match(read(root, 'src/app/dashboard/(main)/tasks/page.tsx'), /export default createEntityListRoute\(taskEntityConfig, NextSparkTemplate\)/)
    assert.match(read(root, 'src/app/dashboard/(main)/posts/[id]/page.tsx'), /export default createEntityDetailRoute\(postsEntityConfig, \[\]\)/)
    assert.equal([...routes].some(route => route.startsWith('dashboard/(main)/[entity]/')), false, 'no runtime dashboard entity route (the /api/v1/[entity] API is core\'s)')
    assert.equal(routes.has('(public)/[...slug]/page.tsx'), false, 'no runtime public catch-all')
    // Public: the item route under the basePath takes the project template, the archive is generated
    assert.match(read(root, 'src/app/(public)/blog/[...slug]/page.tsx'), /export default createPublicItemRoute\(postsEntityConfig, NextSparkTemplate\)/)
    assert.equal(routes.has('(public)/blog/[slug]/page.tsx'), false, 'the template is absorbed by the item route')
    assert.ok(routes.has('(public)/blog/page.tsx'))

    // API: the project's api/ at /api/<path>, no dispatchers, webhook extensions composed
    assert.ok(routes.has('api/ai/usage/route.ts'))
    assert.equal([...routes].some(route => /^api\/v1\/(theme|plugin)\//.test(route)), false, 'no runtime API dispatcher')
    assert.match(read(root, 'src/app/api/v1/billing/webhooks/stripe/route.ts'), /export const POST = createStripeWebhookRoute\(stripeWebhookExtensions\)/)
    assert.match(read(root, 'src/app/api/v1/billing/webhooks/polar/route.ts'), /export \{ POST \} from "@nextsparkjs\/core\/routes\/api\/v1\/billing\/webhooks\/polar\/route"/, 'no polar setting: core\'s route')

    // Cache Components off: no variant is used
    assert.match(read(root, 'src/app/(auth)/login/page.tsx'), /routes\/\(auth\)\/login\/page"/)

    // What was written is what --check expects, and the composed files passed the grammar gate
    assert.deepEqual(await checkHost(config), { ok: true, problems: [] })
    assert.ok(generated.files.filter(file => file.grammar === 'composed-facade').length >= 15, 'entity, layout, item and webhook routes')
  } finally {
    cleanup()
  }
})

test('with cacheComponents on, core\'s Cache Components variants replace the routes Next.js rejects there', async () => {
  const { root, cleanup } = project({ 'next.config.mjs': 'export default { cacheComponents: true }\n' })
  try {
    const { appFiles } = await renderHostFiles(projectHostConfig({ projectRoot: root }))
    const content = path => appFiles.find(file => file.path === `src/app/${path}`).content
    for (const route of ['(auth)/login/page.cc', '(auth)/signup/page.cc', '(public)/docs/[section]/[page]/page.cc', 'superadmin/docs/[section]/[page]/page.cc']) {
      assert.match(content(`${route.replace(/\.cc$/, '')}.tsx`), new RegExp(`routes/${route.replace(/[[\]().]/g, '\\$&')}"`), route)
    }
    // The root layout is core's PPR one, composed with the PPR wrapper; public item pages carry no revalidate
    assert.match(content('layout.tsx'), /from "@nextsparkjs\/core\/routes\/_internal\/root-layout\.ppr"/)
    assert.match(content('(public)/layout.tsx'), /export \{ metadata \} from "@nextsparkjs\/core\/routes\/_internal\/public-layout\.cc"/)
    assert.doesNotMatch(content('(public)/layout.tsx'), /routes\/\(public\)\/layout/)
    assert.doesNotMatch(content('(public)/blog/[...slug]/page.tsx'), /revalidate/)
    for (const file of appFiles) assert.doesNotMatch(file.content, /export const (dynamic|dynamicParams) =/, file.path)
  } finally {
    cleanup()
  }
})

test('a project that puts a route in a namespace it does not own, or a webhook module that is not there, cannot be generated', async () => {
  const { root, cleanup } = project({
    'api/v1/mine/route.ts': ROUTE,
    'api/plugins/x/route.ts': ROUTE,
    'nextspark.config.ts': "export default { billing: { webhookExtensions: { stripe: './lib/billing/nowhere' } } }\n",
  })
  try {
    await assert.rejects(renderHostFiles(projectHostConfig({ projectRoot: root })), error => {
      assert.ok(error instanceof PrepareError)
      assert.deepEqual(error.diagnostics.map(d => d.code).sort(), ['NS_HOST_API_NAMESPACE', 'NS_HOST_API_NAMESPACE', 'NS_HOST_WEBHOOK_EXTENSIONS_MISSING'])
      return true
    })
  } finally {
    cleanup()
  }
})

