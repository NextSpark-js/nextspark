const GROUPS = {
  'layout.tsx': ['withRootLayout', 'root-layout'],
  '(auth)/layout.tsx': ['withAuthMessages', 'auth-layout'],
  '(public)/layout.tsx': ['withPublicMessages', 'public-layout'],
  'superadmin/layout.tsx': ['withSuperadminGuard', 'superadmin-layout'],
  'devtools/layout.tsx': ['withDevtoolsGuard', 'devtools-layout'],
}

test('every group layout override is composed with core\'s wrapper; the role-guarded groups only through the guard wrappers', async () => {
  const { root, cleanup } = project(Object.fromEntries(Object.keys(GROUPS).map(target => [`templates/${target}`, LAYOUT])))
  try {
    const { appFiles } = await renderHostFiles(projectHostConfig({ projectRoot: root }))
    for (const [target, [wrapper, module]] of Object.entries(GROUPS)) {
      const content = at(appFiles, `src/app/${target}`)
      assert.match(content, new RegExp(`import \\{ ${wrapper} \\} from "@nextsparkjs/core/routes/_internal/${module}"`), target)
      assert.match(content, new RegExp(`export default ${wrapper}\\(NextSparkTemplate\\)`), target)
      if (wrapper.endsWith('Guard')) assert.equal(content.includes('Messages(NextSparkTemplate)'), false, `${target}: a guarded group is never wrapped in messages alone`)
    }
    assert.equal(/withSuperadminMessages|withDevtoolsMessages/.test(appFiles.map(file => file.content).join('\n')), false)
  } finally {
    cleanup()
  }
})

test('a project layout over a fully protected core layout (the dashboard\'s) is refused, and a protected route is never silently replaced', async () => {
  const { root, cleanup } = project({ 'templates/dashboard/layout.tsx': LAYOUT })
  try {
    await assert.rejects(renderHostFiles(projectHostConfig({ projectRoot: root })), error => {
      assert.ok(error instanceof PrepareError)
      assert.deepEqual(error.diagnostics.map(d => d.code), ['NS_HOST_PROTECTED_ROUTE'])
      assert.match(error.message, /dashboard\/layout\.tsx/)
      return true
    })
  } finally {
    cleanup()
  }
})

