import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { resolveHostMode } from '../mode.mjs'
import { GENERATION_DIAGNOSTICS, GENERATION_FILE, readGeneration } from '../generation.mjs'
import { prepareHost } from '../prepare.mjs'
import { hasCoreRouteManifest } from '../core-routes.mjs'
import { PAGE, read, snapshot, tempHost, write } from './host-helpers.mjs'

const CORE_ROOT = join(import.meta.dirname, '../../../../..')
const PREPARE_CLI = join(CORE_ROOT, 'scripts/build/registry/host/prepare-cli.mjs')

function project({ legacyApp = false } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'nextspark-host-mode-'))
  write(root, 'nextspark.config.ts', 'export default { plugins: [] }\n')
  write(root, 'package.json', JSON.stringify({ name: 'host-mode', dependencies: { next: '16.3.5' } }))
  write(root, 'templates/pricing/page.tsx', PAGE('Pricing'))
  if (legacyApp) write(root, 'src/app/layout.tsx', 'export default function Layout({ children }) { return children }\n')
  return { root, cleanup: () => rmSync(root, { recursive: true, force: true }) }
}

const run = (root, args) => spawnSync(process.execPath, [PREPARE_CLI, ...args], { cwd: root, encoding: 'utf8', timeout: 240_000 })

test('resolveHostMode: host for no src/app, placeholders only, or a valid record; legacy-app for a committed tree or an invalid record; no-manifest without core routes', () => {
  assert.equal(hasCoreRouteManifest(CORE_ROOT), true, 'this core ships its route manifest (stage 2)')
  const { root, cleanup } = project()
  const mode = () => resolveHostMode({ coreRoot: CORE_ROOT, projectRoot: root }).mode
  try {
    assert.equal(mode(), 'host')
    mkdirSync(join(root, 'src/app/(empty)'), { recursive: true })
    write(root, 'src/app/.gitkeep', '')
    write(root, 'src/app/README.md', '# generated by nextspark prepare\n')
    write(root, 'src/app/(empty)/.DS_Store', '')
    assert.equal(mode(), 'host', 'empty directories and placeholders only')
    write(root, 'src/app/layout.tsx', 'export default function Layout({ children }) { return children }\n')
    const legacy = resolveHostMode({ coreRoot: CORE_ROOT, projectRoot: root })
    assert.deepEqual(Object.keys(legacy).sort(), ['mode', 'reason'])
    assert.equal(legacy.mode, 'legacy-app')
    for (const invalid of ['{}', 'not json', JSON.stringify({ schemaVersion: 1, files: { '../package.json': 'x' } }), JSON.stringify({ schemaVersion: 99, files: {} })]) {
      write(root, GENERATION_FILE, invalid)
      assert.equal(mode(), 'legacy-app', `an invalid record is no ownership: ${invalid}`)
    }
    write(root, GENERATION_FILE, JSON.stringify({ schemaVersion: 1, generator: 'nextspark prepare', mode: 'production', versions: {}, inputs: { hash: null, files: {} }, files: { 'src/app/layout.tsx': 'hash' } }))
    assert.equal(mode(), 'host', 'a valid record selects host mode (publication then proves each file)')

    const bare = mkdtempSync(join(tmpdir(), 'nextspark-bare-core-'))
    write(bare, 'package.json', JSON.stringify({ name: '@nextsparkjs/core', exports: { '.': './dist/index.js' } }))
    assert.equal(resolveHostMode({ coreRoot: bare, projectRoot: root }).mode, 'no-manifest')
    rmSync(bare, { recursive: true, force: true })
  } finally {
    cleanup()
  }
})

test('a leftover VALID record next to a foreign src/app selects host mode, and prepare refuses before writing: the legacy layout is never overwritten', async () => {
  const host = tempHost({ 'templates/about/page.tsx': PAGE('About') })
  try {
    await prepareHost(host.config)
    assert.ok(readGeneration(host.hostRoot).files['src/app/layout.tsx'], 'the record lists layout.tsx')
    rmSync(join(host.hostRoot, 'src/app'), { recursive: true, force: true })
    const legacyLayout = 'export default function MyLegacyLayout({ children }) { return children }\n'
    write(host.hostRoot, 'src/app/layout.tsx', legacyLayout)
    assert.equal(resolveHostMode({ coreRoot: CORE_ROOT, projectRoot: host.hostRoot }).mode, 'host')
    const before = snapshot(host.hostRoot)
    await assert.rejects(prepareHost(host.config), error => {
      assert.deepEqual(error.diagnostics.map(d => d.code), [GENERATION_DIAGNOSTICS.FOREIGN])
      assert.deepEqual(error.diagnostics[0].files, ['src/app/layout.tsx'])
      return true
    })
    assert.equal(read(host.hostRoot, 'src/app/layout.tsx'), legacyLayout)
    const after = snapshot(host.hostRoot)
    delete before['.nextspark/generation.json']
    delete after['.nextspark/generation.json']
    assert.deepEqual(after, before, 'nothing written or deleted')
  } finally {
    host.cleanup()
  }
})

test('with a valid record, a generated file edited by hand is foreign: never overwritten nor deleted, and named', async () => {
  const host = tempHost({ 'templates/about/page.tsx': PAGE('About'), 'templates/gone/page.tsx': PAGE('Gone') })
  try {
    await prepareHost(host.config)
    write(host.hostRoot, 'src/app/about/page.tsx', '// my hand edit\n')
    write(host.hostRoot, 'src/app/gone/page.tsx', '// edited, and its template is being removed\n')
    rmSync(join(host.source, 'templates/gone'), { recursive: true })
    await assert.rejects(prepareHost(host.config), error => {
      assert.deepEqual(error.diagnostics[0].files, ['src/app/about/page.tsx', 'src/app/gone/page.tsx'])
      assert.match(error.message, /edited since it generated them/)
      return true
    })
    assert.equal(read(host.hostRoot, 'src/app/about/page.tsx'), '// my hand edit\n')
    assert.equal(read(host.hostRoot, 'src/app/gone/page.tsx'), '// edited, and its template is being removed\n', 'a stale file is deleted only while it is still NextSpark\'s')
  } finally {
    host.cleanup()
  }
})

test('placeholders in src/app (.gitkeep, README.md) are left untouched by a generation', async () => {
  const host = tempHost({ 'templates/about/page.tsx': PAGE('About') })
  try {
    write(host.hostRoot, 'src/app/.gitkeep', '')
    write(host.hostRoot, 'src/app/README.md', '# src/app is generated\n')
    await prepareHost(host.config)
    assert.equal(read(host.hostRoot, 'src/app/README.md'), '# src/app is generated\n')
    assert.equal(existsSync(join(host.hostRoot, 'src/app/.gitkeep')), true)
    assert.equal(readGeneration(host.hostRoot).files['src/app/README.md'], undefined, 'not owned')
  } finally {
    host.cleanup()
  }
})

test('a committed app tree is not prepared: check, prepare, production and watch fail pointing to nextspark migrate, and nothing is written', { timeout: 300_000 }, () => {
  const { root, cleanup } = project({ legacyApp: true })
  try {
    for (const args of [['--check'], [], ['--production'], ['--watch'], ['--check', '--dev']]) {
      const result = run(root, args)
      assert.equal(result.status, 1, `${args.join(' ')}: ${result.stdout}${result.stderr}`)
      assert.match(result.stderr, /src\/app holds a committed app tree that nextspark did not generate/, args.join(' '))
      assert.match(result.stderr, /nextspark migrate/, args.join(' '))
    }
    assert.equal(existsSync(join(root, '.nextspark')), false, 'nothing was written')
    assert.equal(read(root, 'src/app/layout.tsx'), 'export default function Layout({ children }) { return children }\n', 'the committed tree is untouched')
  } finally {
    cleanup()
  }
})

test('with the real core manifest, a project without src/app (or only placeholders) is generated whole: fresh check, and a second run writes nothing', { timeout: 300_000 }, () => {
  const { root, cleanup } = project()
  try {
    write(root, 'src/app/.gitkeep', '')
    assert.equal(run(root, ['--check']).status, 1, 'not prepared yet')
    const first = run(root, ['--production'])
    assert.equal(first.status, 0, `${first.stdout}\n${first.stderr}`)
    assert.match(first.stdout, /Generated src\/app \((\d+) files\)/)
    const files = Number(/Generated src\/app \((\d+) files\)/.exec(first.stdout)[1])
    assert.ok(files > 150, `${files} files: core's routes plus templates/pricing`)
    assert.ok(existsSync(join(root, 'src/app/pricing/page.tsx')))
    assert.ok(existsSync(join(root, 'src/app/(auth)/login/page.tsx')))
    assert.ok(existsSync(join(root, 'src/app/.gitkeep')), 'the placeholder is untouched')
    const fresh = run(root, ['--check'])
    assert.equal(fresh.status, 0, fresh.stderr)
    const second = run(root, ['--production'])
    assert.match(second.stdout, / 0 written, 0 deleted, \d+ unchanged/)
  } finally {
    cleanup()
  }
})
