/**
 * Tests for the generated-module gate: generated facades and registries must stay inside a small
 * allowed grammar, so no runtime selection of a module can be expressed in them at all - the
 * review's resolver bypasses included - while every facade the emitter can produce and every
 * fixture registry passes.
 *
 * Run: node --test packages/core/scripts/build/registry/host/__tests__/static-imports.test.mjs
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { checkGeneratedModule } from '../static-imports.mjs'
import { renderEntityRegistry } from '../../../../../tests/fixtures/host-conformance/generate.mjs'

const CORE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '../../../../..')
const FIXTURE = join(CORE_ROOT, 'tests/fixtures/host-conformance')
const check = (source, grammar, file = grammar === 'facade' ? '/virtual/src/app/page.tsx' : '/virtual/.nextspark/registries/r.ts') =>
  checkGeneratedModule({ source, file, grammar, projectRoot: CORE_ROOT })

// The review's bypasses of the former denylist, plus the former line-regex misses.
const BYPASSES = {
  'Reflect.get': "import { REGISTRY } from '@/r'\nexport default Reflect.get(REGISTRY, routeName)",
  'computed destructuring': "import { REGISTRY } from '@/r'\nconst { [routeName]: Page } = REGISTRY\nexport default Page",
  'Object.entries(...).find': "import { REGISTRY } from '@/r'\nexport default Object.entries(REGISTRY).find(([key]) => key === routeName)[1]",
  'new Map(...).get': "import { REGISTRY } from '@/r'\nexport default new Map(Object.entries(REGISTRY)).get(routeName)",
  'Object.values(...).find': "import { REGISTRY } from '@/r'\nexport default Object.values(REGISTRY).find(page => page.route === routeName)",
  'spread + switch': "import { REGISTRY } from '@/r'\nconst all = { ...REGISTRY }\nlet Page\nswitch (routeName) { case 'a': Page = all.a; break }\nexport default Page",
  'optional computed access': "import { REGISTRY } from '@/r'\nexport default REGISTRY?.[routeName]",
  'multiline computed access': "import { REGISTRY } from '@/r'\nexport default REGISTRY[\n  routeName\n]",
  'dynamic import': 'export default () => import(path)',
  'require': 'export default require(name)',
  'getTemplateOrDefault': "import { getTemplateOrDefault } from '@/r'\nexport default getTemplateOrDefault('app/page.tsx', Page)",
  'any call, whatever its name': "import { getPageTitle } from '@/r'\nexport const title = getPageTitle('home')",
  'eval': "export default eval('x')",
  'export * from': "export * from '@/templates/page'",
  'export * as ns from': "export * as page from '@/templates/page'",
  'namespace import': "import * as all from '@/templates/page'\nexport { all }",
  'side-effect import': "import '@/templates/page'",
  'function declaration': 'export function GET() { return new Response() }',
  'class declaration': 'export class Page {}',
  'export default expression': "import Page from '@/templates/page'\nexport default Page",
  'non-exported const': "const a = 1\nexport { a }",
  'export of a non-imported name': "export { routeName as default }",
  'let': 'export let revalidate = 60',
  'if statement': "import { A } from '@/a'\nif (A) {}",
  'other directive': "'use server'\nexport { default } from '@/templates/page'",
}

for (const [label, source] of Object.entries(BYPASSES)) {
  test(`facade grammar rejects ${label}`, async () => {
    const violations = await check(source, 'facade')
    assert.ok(violations.length > 0, `accepted: ${source}`)
    assert.ok(violations.every(violation => violation.line >= 1 && violation.kind && violation.text))
  })
  test(`registry grammar rejects ${label}`, async () => {
    assert.ok((await check(source, 'registry')).length > 0, `accepted: ${source}`)
  })
}

const FACADE_LITERAL_REJECTS = ['-1', '(60)', 'Number(60)', 'sixty', '`a${b}`', 'Infinity', '[...xs]', '{ a }', '{ [k]: 1 }', '{ m() {} }']
test('facade grammar accepts exactly the literals Next reads (evaluateNextLiteral)', async () => {
  for (const literal of FACADE_LITERAL_REJECTS) {
    assert.ok((await check(`export const revalidate = ${literal}`, 'facade')).length > 0, literal)
  }
  for (const literal of ['60', 'false', "'force-static'", "['iad1']", '{ "level": "warning" }', 'null', 'undefined', '/a/g', '`plain`']) {
    assert.deepEqual(await check(`export const x = ${literal}`, 'facade'), [], literal)
  }
})

test('facade grammar accepts every shape the emitter writes', async () => {
  for (const source of [
    '// Generated by NextSpark from @/x. Do not edit.\nexport { default } from "@/templates/posts/[slug]/page"\nexport { generateMetadata, generateStaticParams } from "@/templates/posts/[slug]/page"\nexport const revalidate = 60',
    "// header\n'use client'\n\nexport { default } from \"@fixture-core/app/error\"",
    'export { default } from "@/x"\nimport { generateStaticParams as listSlugs } from "@/x"\nexport { listSlugs as generateStaticParams }',
    'export { GET, POST } from "@/api/notes/route"\nexport const dynamic = "force-dynamic"\nexport const preferredRegion = ["iad1"]',
    "import type { Metadata } from 'next'\nexport { default } from '@/x'",
  ]) {
    assert.deepEqual(await check(source, 'facade'), [], source)
  }
})

test('registry grammar accepts the fixture registries, generated and hand-written', async () => {
  for (const [exportName, importName, file] of [['ENTITY_REGISTRY', 'entity', 'entity'], ['CLIENT_ENTITY_REGISTRY', 'clientEntity', 'client']]) {
    assert.deepEqual(await check(renderEntityRegistry(exportName, importName, file, ['notes', 'posts']), 'registry'), [])
  }
  for (const name of ['entities.server.ts', 'entities.client.ts']) {
    assert.deepEqual(await check(await readFile(join(FIXTURE, 'manual/registries', name), 'utf8'), 'registry', name), [], name)
  }
})

test('registry grammar: literal nesting and imported leaves are fine, anything computed is not', async () => {
  const ok = "import { a } from '@/a'\nimport B from '@/b'\nexport const R = { a, b: B, list: [a, 'x', 1, true, null], nested: { 'k-1': { deep: B } }, 2: `t` } as const"
  assert.deepEqual(await check(ok, 'registry'), [])
  for (const bad of [
    "import { a } from '@/a'\nexport const R = { [a]: 1 }",
    "import { a } from '@/a'\nexport const R = { ...a }",
    "import { a } from '@/a'\nexport const R = { get x() { return a } }",
    "import { a } from '@/a'\nexport const R = { x: a.b }",
    "import { a } from '@/a'\nexport const R = { x: a() }",
    'export const R = { x: notImported }',
    'export const R = { notImported }',
    "import { a } from '@/a'\nexport const R = [...a]",
    "import { a } from '@/a'\nexport const R = a",
    'export const R = 1',
    "export { a } from '@/a'",
    "'use client'\nexport const R = {}",
  ]) {
    assert.ok((await check(bad, 'registry')).length > 0, bad)
  }
})

test('an unparseable file is itself a violation', async () => {
  assert.equal((await check('export const = ;', 'facade'))[0].kind, 'parse-error')
})

test('dev-facade grammar: the facade grammar plus exactly one composition with the dev status wrapper', async () => {
  const layout =
    '// Generated\nimport NextSparkSourceLayout from "@nextsparkjs/core/routes/layout"\n' +
    "import { withGenerationStatus } from './_nextspark/generation-status'\n" +
    'export default withGenerationStatus(NextSparkSourceLayout)\nexport { metadata } from "@nextsparkjs/core/routes/layout"\n'
  assert.deepEqual(await check(layout, 'dev-facade'), [])
  assert.deepEqual((await check(layout, 'facade')).map(v => v.kind), ['statement'], 'production facades never carry it')
  const base = 'import Source from "@/templates/layout"\n'
  for (const bad of [
    "import './_nextspark/generation-status'\n",
    `${base}import { withGenerationStatus } from './other'\nexport default withGenerationStatus(Source)\n`,
    `${base}import { other } from './_nextspark/generation-status'\nexport default other(Source)\n`,
    `${base}import { withGenerationStatus } from './_nextspark/generation-status'\nexport default withGenerationStatus(Source, 1)\n`,
    `${base}import { withGenerationStatus } from './_nextspark/generation-status'\nexport default withGenerationStatus(process.env.X)\n`,
    `${base}import { withGenerationStatus } from './_nextspark/generation-status'\nexport default withGenerationStatus(Source)\nexport default withGenerationStatus(Source)\n`,
    `import { Source } from "@/templates/layout"\nimport { withGenerationStatus } from './_nextspark/generation-status'\nexport default withGenerationStatus(Source)\n`,
    "import { a } from '@/a'\nexport const R = a.b\n",
  ]) {
    assert.ok((await check(bad, 'dev-facade')).length > 0, bad)
  }
})
