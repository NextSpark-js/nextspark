/**
 * #228: parallel route slots (`@modal`) in a project's templates. The host generates them beside the layout that renders
 * them, core's composed layouts hand them to the project's layout (see tests/jest/routes/layout-slots.test.tsx), and a slot
 * with no `default` file is named before Next.js fails the build for it.
 *
 * Run: node --test packages/core/scripts/build/registry/host/__tests__/host-slots.test.mjs
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'

import { PLAN_NOTICES, slotDefaultNotices } from '../plan.mjs'
import { prepareHost, projectHostConfig } from '../prepare.mjs'
import { CORE_ROOT, PAGE, read, tempHost } from './host-helpers.mjs'

const LAYOUT = 'export default function Layout({ children, modal }) { return <>{children}<aside>{modal}</aside></>}\n'
const DEFAULT = 'export default function Default() { return null }\n'
const codes = notices => notices.map(notice => notice.code)

test('a project layout with an @modal slot: the slot is generated beside it, and nothing is said when it has a default', async () => {
  const host = tempHost({
    'templates/layout.tsx': LAYOUT,
    'templates/@modal/page.tsx': PAGE('Modal'),
    'templates/@modal/default.tsx': DEFAULT,
    'templates/@modal/(.)photos/[id]/page.tsx': PAGE('Photo'),
  })
  try {
    const result = await prepareHost(host.config, { mode: 'production' })
    assert.ok(result.files.some(file => file.path === 'src/app/layout.tsx'))
    for (const file of ['@modal/page.tsx', '@modal/default.tsx', '@modal/(.)photos/[id]/page.tsx']) assert.ok(existsSync(join(host.hostRoot, 'src/app', file)), file)
    assert.equal(read(host.hostRoot, 'src/app/@modal/default.tsx'), '// Generated by NextSpark from @/templates/@modal/default. Do not edit: regenerated on every build.\nexport { default } from "@/templates/@modal/default"\n')
    assert.deepEqual(codes(result.notices ?? []).filter(code => code === PLAN_NOTICES.SLOT_DEFAULT_MISSING), [])
  } finally {
    host.cleanup()
  }
})

test('a slot with no default file is named, with the file to add, for every slot at any depth', async () => {
  const host = tempHost({
    'templates/layout.tsx': LAYOUT,
    'templates/@modal/page.tsx': PAGE('Modal'),
    'templates/dashboard/layout.tsx': LAYOUT,
    'templates/dashboard/@panel/(..)settings/page.tsx': PAGE('Panel'),
    'templates/dashboard/@done/page.tsx': PAGE('Done'),
    'templates/dashboard/@done/default.tsx': DEFAULT,
  })
  try {
    const result = await prepareHost(host.config, { mode: 'production' })
    const missing = (result.notices ?? []).filter(notice => notice.code === PLAN_NOTICES.SLOT_DEFAULT_MISSING)
    assert.deepEqual(missing.map(notice => notice.target), ['@modal/default.tsx', 'dashboard/@panel/default.tsx'])
    assert.match(missing[0].message, /^src\/app\/@modal: the parallel route slot "@modal" has no default file, and Next\.js fails the build without one\. Add \.?\/?templates\/@modal\/default\.tsx, returning null/)
    assert.match(missing[1].message, /Add \.?\/?templates\/dashboard\/@panel\/default\.tsx/)
    assert.deepEqual(missing[1].by.map(source => source.replace(/^\.\//, '')), ['templates/dashboard/@panel/(..)settings/page.tsx'])
    // a notice, not a failure: the files are written, and Next's own error is what the user would have met
    assert.ok(existsSync(join(host.hostRoot, 'src/app/@modal/page.tsx')))
  } finally {
    host.cleanup()
  }
})

test('slotDefaultNotices reads the plan: a default in the slot directory is the one that counts', () => {
  const route = (target, kind = 'page') => ({ kind, target, source: `templates/${target}`, layer: 'project' })
  assert.deepEqual(slotDefaultNotices([route('page.tsx'), route('about/page.tsx')]), [])
  assert.deepEqual(slotDefaultNotices([route('@a/page.tsx'), route('@a/default.tsx', 'default')]), [])
  // a default in another slot, or deeper in the same one, does not cover it
  assert.equal(slotDefaultNotices([route('@a/page.tsx'), route('@b/default.tsx', 'default'), route('@a/x/default.tsx', 'default')]).length, 1)
  assert.equal(slotDefaultNotices([route('x/@a/page.tsx')])[0].target, 'x/@a/default.tsx')
})

/** The real core's route manifest: its layouts are composed with the project's. */
test('with the real core manifest, the root and group layouts compose a project layout and keep its slots', { timeout: 180_000 }, async () => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'nextspark-slots-')))
  const put = (path, content) => {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), content)
  }
  put('nextspark.config.ts', 'export default { plugins: [] }\n')
  put('package.json', JSON.stringify({ name: 'slots-project', dependencies: { next: '16.4.2' } }))
  put('config/theme.config.ts', "export const slotsThemeConfig = { name: 'slots' }\n")
  put('templates/layout.tsx', LAYOUT)
  put('templates/@modal/page.tsx', PAGE('Modal'))
  put('templates/@modal/default.tsx', DEFAULT)
  put('templates/(auth)/layout.tsx', LAYOUT)
  put('templates/(auth)/@aside/page.tsx', PAGE('Aside'))
  put('templates/(auth)/@aside/default.tsx', DEFAULT)
  try {
    const host = { ...projectHostConfig({ projectRoot: root, coreRoot: CORE_ROOT }) }
    await prepareHost(host, { mode: 'production' })
    const layout = read(root, 'src/app/layout.tsx')
    assert.match(layout, /import \{ withRootLayout \} from "@nextsparkjs\/core\/routes\/_internal\/root-layout"/)
    assert.match(layout, /export default withRootLayout\(/)
    assert.match(read(root, 'src/app/(auth)/layout.tsx'), /withAuthMessages\(/)
    for (const file of ['@modal/page.tsx', '@modal/default.tsx', '(auth)/@aside/page.tsx', '(auth)/@aside/default.tsx']) assert.ok(existsSync(join(root, 'src/app', file)), file)
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})
