/**
 * Host rendering (#203): one facade per planned route, through the stage-1 facade emitter.
 *
 * Nothing is written here. The result is the list of files of the generated `src/app` with
 * their content, or every diagnostic of every route that cannot be emitted.
 *
 * Cache modes: a real project's host has one `cacheComponents` value (checked when known). A
 * host that builds both ways (the conformance fixture) passes `modes: ['isr', 'cc']`; a route
 * valid in both is then checked against each, and a mode-only route (`page.cc.tsx`) against its
 * own mode.
 *
 * Development status (`nextspark dev` only): when a regeneration fails, the dev server keeps
 * serving the last valid generation, and the diagnostic must still reach the browser without
 * pretending the change was applied. With `devStatus`, the host gets three fixed files in a
 * private folder (`src/app/_nextspark/`, never routes):
 *   - `generation-diagnostic.ts`: `export const generationDiagnostic = "<text>"`, "" when healthy -
 *     the only file the watcher rewrites on a failure (and publication restores);
 *   - `generation-status-reporter.tsx`: a 'use client' component that, while the diagnostic is
 *     non-empty, renders a fixed dev panel with it (React state: it survives Fast Refresh, which
 *     clears Next's own issue list) and calls console.error(diagnostic) once per diagnostic, which
 *     Next's dev indicator lists as an issue; HMR re-renders it with "" once fixed and it disappears;
 *   - `generation-status.tsx`: `withGenerationStatus(Layout)`, which renders the root layout with
 *     the reporter placed before its children.
 * The root layout facade of a dev generation composes the core/project layout with it
 * (`dev-facade` grammar: `export default withGenerationStatus(Layout)`, both statically imported).
 * Nothing throws, so every route keeps rendering. A production preparation never passes
 * `devStatus`: production builds carry none of these files and no composition.
 *
 * @module core/scripts/build/registry/host/render
 */

import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'

import { FacadeEmitError, analyzeRouteSource, emitFacade, loadNextSegmentConfig, planFacade } from './facade-emitter.mjs'
import { DEV_STATUS_SPECIFIER, validateGeneratedModule } from './static-imports.mjs'
import { loadTypeScriptFor } from '../shared/typescript-compiler.mjs'

export const APP_DIR = 'src/app'
export const DEV_DIR = `${APP_DIR}/_nextspark`
export const DEV_STATUS_FILE = `${DEV_DIR}/generation-status.tsx`
export const DEV_REPORTER_FILE = `${DEV_DIR}/generation-status-reporter.tsx`
export const DEV_DIAGNOSTIC_FILE = `${DEV_DIR}/generation-diagnostic.ts`
const ROOT_LAYOUT = /^layout\.[a-z.]+$/
const DEV_HEADER = '// Generated by NextSpark for `nextspark dev` only; never part of a production build. Do not edit.\n'

/**
 * The fixed development files (not facades: validated by being exactly this text). Only the
 * diagnostic module varies.
 */
export const DEV_RUNTIME_FILES = Object.freeze({
  [DEV_REPORTER_FILE]:
    "'use client'\n" +
    DEV_HEADER +
    "import { useEffect, useState } from 'react'\n\n" +
    '/**\n' +
    ' * Shows a failed regeneration in the browser while the previous generation keeps being served:\n' +
    " * a fixed panel (React state, so it survives Fast Refresh, which clears Next's issue list) and a\n" +
    ' * console.error that Next lists as a dev issue. Renders nothing while the generation is healthy.\n' +
    ' */\n' +
    'export function GenerationStatusReporter({ diagnostic }: { diagnostic: string }) {\n' +
    "  const [dismissed, setDismissed] = useState('')\n" +
    '  useEffect(() => {\n' +
    '    if (diagnostic) console.error(diagnostic)\n' +
    '  }, [diagnostic])\n' +
    '  if (!diagnostic || dismissed === diagnostic) return null\n' +
    '  return (\n' +
    '    <div\n' +
    '      role="alert"\n' +
    '      data-nextspark-generation-status=""\n' +
    "      style={{ position: 'fixed', right: 16, bottom: 72, zIndex: 2147483646, maxWidth: 560, maxHeight: '50vh', overflow: 'auto', padding: '12px 14px', borderRadius: 8, border: '1px solid #e5484d', background: '#fff5f5', color: '#8e1b1b', boxShadow: '0 4px 16px rgba(0, 0, 0, 0.15)', font: '12px/1.5 ui-monospace, SFMono-Regular, Menlo, monospace', whiteSpace: 'pre-wrap' }}\n" +
    '    >\n' +
    '      <button\n' +
    '        type="button"\n' +
    '        aria-label="Dismiss until the diagnostic changes"\n' +
    '        onClick={() => setDismissed(diagnostic)}\n' +
    "        style={{ float: 'right', marginLeft: 8, border: 0, background: 'transparent', color: 'inherit', cursor: 'pointer', font: 'inherit' }}\n" +
    '      >\n' +
    '        ×\n' +
    '      </button>\n' +
    '      {diagnostic}\n' +
    '    </div>\n' +
    '  )\n' +
    '}\n',
  [DEV_STATUS_FILE]:
    DEV_HEADER +
    "import type { ComponentType, ReactNode } from 'react'\n" +
    "import { GenerationStatusReporter } from './generation-status-reporter'\n" +
    "import { generationDiagnostic } from './generation-diagnostic'\n\n" +
    '/** The root layout, with the generation status reporter rendered before its children. */\n' +
    '// eslint-disable-next-line @typescript-eslint/no-explicit-any\n' +
    'export function withGenerationStatus(Layout: ComponentType<any>) {\n' +
    '  return function NextSparkDevRootLayout(props: { children?: ReactNode }) {\n' +
    '    return (\n' +
    '      <Layout {...props}>\n' +
    '        <GenerationStatusReporter diagnostic={generationDiagnostic} />\n' +
    '        {props.children}\n' +
    '      </Layout>\n' +
    '    )\n' +
    '  }\n' +
    '}\n',
})

/** The diagnostic module: "" for a healthy generation, the diagnostic text after a failed regeneration. */
export function devDiagnosticModule(diagnostic = '') {
  return `${DEV_HEADER}export const generationDiagnostic = ${JSON.stringify(diagnostic)}\n`
}

/**
 * What the browser shows while a regeneration fails. Precise about what is not applied: src/app
 * (which route files exist, the names they forward, the segment config copied as literals) stays
 * as last generated, while edits inside modules the existing facades import still reach Next.
 */
export function devFailureDiagnostic(message) {
  return (
    'NextSpark could not regenerate src/app; the dev server keeps serving the previous generation. ' +
    'Until this is fixed, route files added, moved or removed, exports and segment config changed since then are NOT applied ' +
    '(edits inside existing modules still reload as usual).\n' +
    message
  )
}

/**
 * The dev root layout: the emitted facade with its default re-export replaced by the composition.
 * Null when the facade has no plain default re-export (a client root layout cannot be composed).
 */
function composeDevRootLayout(content) {
  const line = /^export \{ default \} from ("[^"\n]+")$/m
  const match = line.exec(content)
  if (!match || content.includes("'use client'")) return null
  return content.replace(
    line,
    `import NextSparkSourceLayout from ${match[1]}\nimport { withGenerationStatus } from '${DEV_STATUS_SPECIFIER}'\nexport default withGenerationStatus(NextSparkSourceLayout)`
  )
}

const sha256 = text => createHash('sha256').update(text).digest('hex')

/**
 * Emit one route: prevalidated against every cache mode it serves, then written by `emitFacade`
 * (which applies the facade grammar gate to its own output).
 */
async function emitRoute(route, source, { projectRoot, modes, cacheComponents, pageExtensions }) {
  const routeModes = route.mode ? [route.mode] : modes
  if (routeModes.length > 0) {
    const analysis = await analyzeRouteSource({ source, file: route.file, projectRoot })
    // A problem every mode has is reported once; one only some modes have names them.
    const byProblem = new Map()
    for (const mode of routeModes) {
      const { diagnostics: found } = planFacade({
        ...route,
        analysis,
        cacheComponents: mode === 'cc',
        pageExtensions,
        nextSegmentConfig: loadNextSegmentConfig(projectRoot),
      })
      for (const diagnostic of found) {
        const key = JSON.stringify([diagnostic.code, diagnostic.line, diagnostic.exportName, diagnostic.message])
        if (!byProblem.has(key)) byProblem.set(key, { diagnostic, modes: [] })
        byProblem.get(key).modes.push(mode)
      }
    }
    const diagnostics = [...byProblem.values()].map(({ diagnostic, modes: found }) =>
      found.length === routeModes.length ? diagnostic : { ...diagnostic, message: `[${found.join(', ')} host] ${diagnostic.message}` }
    )
    if (diagnostics.length > 0) throw new FacadeEmitError(diagnostics)
  }
  const emitted = await emitFacade({
    ...route,
    source,
    projectRoot,
    cacheComponents: routeModes.length === 1 ? routeModes[0] === 'cc' : routeModes.length > 1 ? undefined : cacheComponents,
    pageExtensions,
  })
  return { content: emitted.content, sourceHash: sha256(source) }
}

/**
 * Render every facade of the plan.
 *
 * @param {object} input
 * @param {object[]} input.routes - the plan (`resolveHostPlan`)
 * @param {string} input.projectRoot - where TypeScript and Next.js resolve from
 * @param {string[]} [input.modes] - see the module comment
 * @param {boolean} [input.cacheComponents] - the host's value, when known
 * @param {string[]} [input.pageExtensions] - the host's pageExtensions
 * @param {Map} [input.cache] - reused across calls by the watcher: unchanged sources are not re-parsed
 * @param {boolean} [input.devStatus] - add the development status module (see the module comment)
 * @returns {Promise<{ files: { path: string, content: string, grammar: string }[], diagnostics: object[] }>}
 */
export async function renderHost({ routes, projectRoot, modes = [], cacheComponents, pageExtensions, cache = new Map(), devStatus = false }) {
  const files = []
  const diagnostics = []
  const options = { projectRoot, modes, cacheComponents, pageExtensions }
  const optionsKey = JSON.stringify({ modes, cacheComponents, pageExtensions })

  for (const route of routes) {
    let source
    try {
      source = await readFile(route.file, 'utf8')
    } catch (error) {
      diagnostics.push({ code: 'NS_HOST_SOURCE_UNREADABLE', file: route.file, message: `${route.source ?? route.file}: cannot be read (${error.code ?? error.message})` })
      continue
    }
    const key = `${route.target}\0${route.specifier}\0${route.mode ?? ''}\0${optionsKey}`
    const hit = cache.get(key)
    let content
    if (hit && hit.sourceHash === sha256(source)) {
      content = hit.content
    } else {
      try {
        const emitted = await emitRoute(route, source, options)
        cache.set(key, emitted)
        content = emitted.content
      } catch (error) {
        if (!(error instanceof FacadeEmitError)) throw error
        cache.delete(key)
        for (const diagnostic of error.diagnostics) diagnostics.push({ ...diagnostic, target: route.target, source: route.source })
        continue
      }
    }
    const devLayout = devStatus && ROOT_LAYOUT.test(route.target) ? composeDevRootLayout(content) : null
    files.push({ path: `${APP_DIR}/${route.target}`, content: devLayout ?? content, grammar: devLayout ? 'dev-facade' : 'facade' })
  }

  if (devStatus) {
    files.push(
      { path: DEV_DIAGNOSTIC_FILE, content: devDiagnosticModule(), grammar: 'facade' },
      ...Object.entries(DEV_RUNTIME_FILES).map(([path, content]) => ({ path, content, grammar: 'dev-runtime' }))
    )
  }

  // The composed dev root layout passes its grammar gate here too (validateFiles repeats it).
  if (devStatus && diagnostics.length === 0) {
    const ts = await loadTypeScriptFor(projectRoot)
    for (const file of files.filter(file => file.grammar === 'dev-facade' || file.path === DEV_DIAGNOSTIC_FILE)) {
      for (const violation of validateGeneratedModule({ ts, source: file.content, file: file.path, grammar: file.grammar })) {
        diagnostics.push({ code: 'NS_HOST_VARIABLE_LOOKUP', file: file.path, line: violation.line, message: `${file.path} leaves the allowed grammar (${violation.kind}): ${violation.text}` })
      }
    }
  }

  return { files, diagnostics }
}
