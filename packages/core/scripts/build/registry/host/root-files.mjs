/**
 * The files a host serves at its root (#480), for `createProxy({ rejectUnknownRootFiles: true })`
 *
 * With that option the proxy answers a one-segment request for a file (`/meta.json`, `/wp-login.php`) with an empty 404
 * before any route renders, unless the name is here: a file directly in the project's `public/`, or a root route whose
 * URL has a dot (core's `robots.ts` and `sitemap.ts`, a project's `manifest.ts`, a `templates/llms.txt/route.ts`).
 * The list is taken by `nextspark prepare` (which `nextspark build` runs before `next build`), so it does not know a file
 * written into public/ during or after the build (a serwist or next-pwa service worker, next-sitemap's postbuild
 * sitemaps), nor the sources of next.config `rewrites`, which run after the proxy: with the option on, those get the
 * 404 too. Written with the registries as `.nextspark/registries/root-files.ts`, with the destination of the proxy's
 * not-found rewrite (`NOT_FOUND_REWRITE_PATH`, see `notFoundRewritePath`).
 *
 * @module core/scripts/build/registry/host/root-files
 */

import { readdirSync } from 'node:fs'
import { join } from 'node:path'

import { servedUrlSegments } from './plan.mjs'
import { REGISTRIES_DIR } from './generation.mjs'

/** The URL a root metadata route is served at, by its kind; the image ones (`icon`, `opengraph-image`) have no extension. */
const METADATA_URLS = { robots: 'robots.txt', sitemap: 'sitemap.xml', manifest: 'manifest.webmanifest' }

/**
 * @param {{ routes: Array<{ kind: string, target: string }>, hostRoot: string }} input - the resolved host plan, and the Next app whose public/ is served
 * @returns {string[]} the root names with a dot, sorted
 */
export function rootFileNames({ routes, hostRoot }) {
  const names = new Set()
  let entries = []
  try {
    entries = readdirSync(join(hostRoot, 'public'), { withFileTypes: true })
  } catch (error) {
    if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') throw error
  }
  // A symlink counts too: what it points at is only known when Next serves it
  for (const entry of entries) if (!entry.isDirectory()) names.add(entry.name)
  for (const route of routes) {
    const [first] = servedUrlSegments(route.target)
    if (first === undefined) {
      if (METADATA_URLS[route.kind]) names.add(METADATA_URLS[route.kind])
    } else if (!first.startsWith('[')) {
      names.add(first)
    }
  }
  return [...names].filter(name => name.includes('.')).sort()
}

/** Where the proxy rewrites a request to get the not-found page with a 404 when no route matches it (#480). */
const UNMATCHED_NOT_FOUND_PATH = '/_ns/not-found'
/** Next's own not-found route: 404 in `next start`, but served as a static page with 200 on Vercel. */
const NEXT_NOT_FOUND_PATH = '/_not-found'

/** Whether a route whose URL segments are `segments` serves `path` (segments too): what Next matches, dynamic segments included. */
function servesPath(segments, path) {
  if (segments.length === 0) return path.length === 0
  const [segment, ...rest] = segments
  if (/^\[\[\.\.\.[^\]]+\]\]$/.test(segment)) return true
  if (/^\[\.\.\.[^\]]+\]$/.test(segment)) return path.length > 0
  if (path.length === 0) return false
  if (/^\[[^\]]+\]$/.test(segment)) return servesPath(rest, path.slice(1))
  let name = segment
  try {
    name = decodeURIComponent(segment) // `%5Fns` serves `/_ns`
  } catch {}
  return name === path[0] && !segment.startsWith('_') && servesPath(rest, path.slice(1))
}

/**
 * The destination of the proxy's not-found rewrite (#480): `/_ns/not-found`, which no route matches, so Next answers it
 * 404 with the not-found page, as it answers any unknown URL, in `next start` and on Vercel. A host with a route that
 * matches it (a dynamic route of two or more segments at the root: core's `(public)/[...slug]` for a builder entity at
 * basePath `/` with nested slugs, or a project's `[...x]`, `[[...x]]`, `[a]/[b]`) would answer it from that route, under
 * Cache Components with 200; there it is `/_not-found`, which `next start` answers 404 and Vercel 200.
 *
 * @param {{ routes: Array<{ kind: string, target: string }> }} input - the resolved host plan
 */
export function notFoundRewritePath({ routes }) {
  const path = UNMATCHED_NOT_FOUND_PATH.split('/').filter(Boolean)
  const matched = routes.some(route => (route.kind === 'page' || route.kind === 'route') && servesPath(servedUrlSegments(route.target), path))
  return matched ? NEXT_NOT_FOUND_PATH : UNMATCHED_NOT_FOUND_PATH
}

/** The registry file with the root names and the not-found rewrite destination. */
export function rootFilesRegistry(input) {
  return {
    path: `${REGISTRIES_DIR}/root-files.ts`,
    content: `/**
 * Root files
 *
 * The files and routes with a dot this host serves at its root, read by createProxy({ rejectUnknownRootFiles: true }),
 * and where the proxy rewrites a request for the not-found page with a 404.
 *
 * DO NOT EDIT - This file is auto-generated by nextspark prepare
 */

export const ROOT_FILES = ${JSON.stringify(rootFileNames(input), null, 2)} as readonly string[]

export const NOT_FOUND_REWRITE_PATH = ${JSON.stringify(notFoundRewritePath(input))}
`,
    grammar: null,
  }
}
