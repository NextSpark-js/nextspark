/**
 * The files a host serves at its root (#480), for `createProxy({ rejectUnknownRootFiles: true })`
 *
 * With that option the proxy answers a one-segment request for a file (`/meta.json`, `/wp-login.php`) with an empty 404
 * before any route renders, unless the name is here: a file directly in the project's `public/`, or a root route whose
 * URL has a dot (core's `robots.ts` and `sitemap.ts`, a project's `manifest.ts`, a `templates/llms.txt/route.ts`).
 * The list is taken by `nextspark prepare` (which `nextspark build` runs before `next build`), so it does not know a file
 * written into public/ during or after the build (a serwist or next-pwa service worker, next-sitemap's postbuild
 * sitemaps), nor the sources of next.config `rewrites`, which run after the proxy: with the option on, those get the
 * 404 too. Written with the registries as `.nextspark/registries/root-files.ts`.
 *
 * @module core/scripts/build/registry/host/root-files
 */

import { readdirSync } from 'node:fs'
import { join } from 'node:path'

import { servedUrlSegments } from './plan.mjs'
import { REGISTRIES_DIR } from './generation.mjs'

/** The URL a root metadata route is served at, by its kind; the image ones (`icon`, `opengraph-image`) have no extension. */
const METADATA_URLS = { robots: 'robots.txt', sitemap: 'sitemap.xml', manifest: 'manifest.webmanifest' }

/**
 * @param {{ routes: Array<{ kind: string, target: string }>, hostRoot: string }} input - the resolved host plan, and the Next app whose public/ is served
 * @returns {string[]} the root names with a dot, sorted
 */
export function rootFileNames({ routes, hostRoot }) {
  const names = new Set()
  let entries = []
  try {
    entries = readdirSync(join(hostRoot, 'public'), { withFileTypes: true })
  } catch (error) {
    if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') throw error
  }
  // A symlink counts too: what it points at is only known when Next serves it
  for (const entry of entries) if (!entry.isDirectory()) names.add(entry.name)
  for (const route of routes) {
    const [first] = servedUrlSegments(route.target)
    if (first === undefined) {
      if (METADATA_URLS[route.kind]) names.add(METADATA_URLS[route.kind])
    } else if (!first.startsWith('[')) {
      names.add(first)
    }
  }
  return [...names].filter(name => name.includes('.')).sort()
}

/** The registry file with the root names. */
export function rootFilesRegistry(input) {
  return {
    path: `${REGISTRIES_DIR}/root-files.ts`,
    content: `/**
 * Root files
 *
 * The files and routes with a dot this host serves at its root, read by createProxy({ rejectUnknownRootFiles: true }).
 *
 * DO NOT EDIT - This file is auto-generated by nextspark prepare
 */

export const ROOT_FILES: readonly string[] = ${JSON.stringify(rootFileNames(input), null, 2)}
`,
    grammar: null,
  }
}
