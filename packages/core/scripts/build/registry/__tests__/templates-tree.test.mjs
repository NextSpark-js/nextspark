/**
 * Tests for how the registry build keeps app/(templates): the tree holds exactly
 * what the project's app layouts and theme templates produce now, and anything
 * the build replaces with different content or removes is backed up first.
 *
 * Run: node --test packages/core/scripts/build/registry/__tests__/templates-tree.test.mjs
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { chmod, mkdtemp, mkdir, writeFile, readFile, readdir, stat, rm, symlink } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { join, dirname, relative, sep } from 'node:path'

import { generateMissingPages, planMissingPages } from '../post-build/page-generator.mjs'

const DASHBOARD_LAYOUT = "'use client'\n\nexport default function DashboardLayout({ children }) { return children }\n"
const PAGE = 'export default function Page() { return null }\n'

async function createProject() {
  return mkdtemp(join(tmpdir(), 'nextspark-templates-tree-test-'))
}

async function writeProjectFile(root, relativePath, content) {
  const absolutePath = join(root, relativePath)
  await mkdir(dirname(absolutePath), { recursive: true })
  await writeFile(absolutePath, content, 'utf8')
}

/** A theme template at `contents/themes/testtheme/templates/<relativePath>`, overriding `app/<relativePath>`. */
async function writeTemplate(root, relativePath, templateType, content) {
  await writeProjectFile(root, join('contents/themes/testtheme/templates', relativePath), content)
  return {
    name: relativePath.replace(/\.(tsx|ts)$/, ''),
    themeName: 'testtheme',
    templateType,
    fileName: relativePath.split('/').pop(),
    relativePath,
    appPath: `app/${relativePath}`,
    templatePath: `@/contents/themes/testtheme/templates/${relativePath}`,
    priority: 10
  }
}

/** Every file under .nextspark/backups, as its path inside the backup plus its content. */
async function backedUpFiles(root) {
  const backupsDir = join(root, '.nextspark/backups')
  if (!existsSync(backupsDir)) return []

  const files = []
  for (const run of await readdir(backupsDir, { withFileTypes: true })) {
    if (!run.isDirectory()) continue
    const runDir = join(backupsDir, run.name)
    const walk = async directory => {
      for (const entry of await readdir(directory, { withFileTypes: true })) {
        const path = join(directory, entry.name)
        if (entry.isDirectory()) {
          await walk(path)
        } else {
          files.push({ path: relative(runDir, path).split(sep).join('/'), content: await readFile(path, 'utf8') })
        }
      }
    }
    await walk(runDir)
  }
  return files
}

test('a stale copy of an app layout is refreshed, and what it held is backed up', async () => {
  const root = await createProject()
  try {
    await writeProjectFile(root, 'app/dashboard/layout.tsx', DASHBOARD_LAYOUT)
    await writeProjectFile(root, 'app/(templates)/dashboard/layout.tsx', "'use client'\n// copied by an older release\n")
    const page = await writeTemplate(root, 'dashboard/reports/page.tsx', 'page', PAGE)

    await generateMissingPages([page], { projectRoot: root })

    const copy = await readFile(join(root, 'app/(templates)/dashboard/layout.tsx'), 'utf8')
    assert.match(copy, /^\/\*\*\n \* Generated by the NextSpark registry build: a copy of app\/dashboard\/layout\.tsx/)
    assert.ok(copy.endsWith(DASHBOARD_LAYOUT), 'the copy is the app layout, directive included, after the generated comment')

    assert.deepEqual(await backedUpFiles(root), [
      { path: 'app/(templates)/dashboard/layout.tsx', content: "'use client'\n// copied by an older release\n" }
    ])
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('a layout copy no generated route needs any more is removed, and backed up', async () => {
  const root = await createProject()
  try {
    await writeProjectFile(root, 'app/(templates)/old/layout.tsx', DASHBOARD_LAYOUT)
    const page = await writeTemplate(root, 'pricing/page.tsx', 'page', PAGE)

    await generateMissingPages([page], { projectRoot: root })

    assert.equal(existsSync(join(root, 'app/(templates)/old/layout.tsx')), false)
    assert.equal(existsSync(join(root, 'app/(templates)/old')), false)
    assert.deepEqual(await backedUpFiles(root), [{ path: 'app/(templates)/old/layout.tsx', content: DASHBOARD_LAYOUT }])
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('the route file of a template whose app route now exists is removed, and backed up', async () => {
  const root = await createProject()
  try {
    const page = await writeTemplate(root, 'pricing/page.tsx', 'page', PAGE)
    await generateMissingPages([page], { projectRoot: root })
    const generated = await readFile(join(root, 'app/(templates)/pricing/page.tsx'), 'utf8')

    await writeProjectFile(root, 'app/pricing/page.tsx', PAGE)
    await generateMissingPages([page], { projectRoot: root })

    assert.equal(existsSync(join(root, 'app/(templates)/pricing/page.tsx')), false)
    assert.deepEqual(await backedUpFiles(root), [{ path: 'app/(templates)/pricing/page.tsx', content: generated }])
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('regenerating a tree that is already up to date writes nothing and backs nothing up', async () => {
  const root = await createProject()
  try {
    await writeProjectFile(root, 'app/dashboard/layout.tsx', DASHBOARD_LAYOUT)
    const page = await writeTemplate(root, 'dashboard/reports/page.tsx', 'page', PAGE)
    const layout = await writeTemplate(root, 'dashboard/reports/layout.tsx', 'layout', "export const metadata = { title: 'Reports' }\n")

    await generateMissingPages([page, layout], { projectRoot: root })
    const generatedFiles = ['dashboard/layout.tsx', 'dashboard/reports/page.tsx', 'dashboard/reports/layout.tsx']
      .map(file => join(root, 'app/(templates)', file))
    const modifiedTimes = await Promise.all(generatedFiles.map(async file => (await stat(file)).mtimeMs))

    await generateMissingPages([page, layout], { projectRoot: root })

    assert.deepEqual(await Promise.all(generatedFiles.map(async file => (await stat(file)).mtimeMs)), modifiedTimes)
    assert.equal(existsSync(join(root, '.nextspark/backups')), false)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('two builds in the same millisecond keep both backups', async () => {
  const root = await createProject()
  const toISOString = Date.prototype.toISOString
  Date.prototype.toISOString = () => '2026-01-01T00:00:00.000Z'
  try {
    await writeProjectFile(root, 'app/dashboard/layout.tsx', DASHBOARD_LAYOUT)
    const page = await writeTemplate(root, 'dashboard/reports/page.tsx', 'page', PAGE)

    await writeProjectFile(root, 'app/(templates)/dashboard/layout.tsx', '// first hand edit\n')
    await generateMissingPages([page], { projectRoot: root })
    await writeProjectFile(root, 'app/(templates)/dashboard/layout.tsx', '// second hand edit\n')
    await generateMissingPages([page], { projectRoot: root })

    assert.deepEqual(
      (await backedUpFiles(root)).map(({ content }) => content).sort(),
      ['// first hand edit\n', '// second hand edit\n']
    )
  } finally {
    Date.prototype.toISOString = toISOString
    await rm(root, { recursive: true, force: true })
  }
})

