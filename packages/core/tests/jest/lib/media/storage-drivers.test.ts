describe('logStorageAtStartup', () => {
  afterEach(() => jest.restoreAllMocks())

  it('warns about volumes and instances for the local driver, once per process', () => {
    jest.isolateModules(() => {
      const storage = require('@/core/lib/media/storage') as typeof import('@/core/lib/media/storage')
      const warn = jest.spyOn(console, 'warn').mockImplementation(() => {})
      storage.logStorageAtStartup(env({ STORAGE_DRIVER: 'local', UPLOADS_DIR: '/data/uploads' }))
      expect(warn).toHaveBeenCalledWith(expect.stringMatching(/STORAGE_DRIVER=local .*\/data\/uploads.*persistent volume.*not shared between instances/))
      storage.selectStorageDriver(env({ STORAGE_DRIVER: 'local', UPLOADS_DIR: '/data/uploads' }))
      expect(warn).toHaveBeenCalledTimes(1)
    })
  })

  it('warns at the first selection when the startup log did not run (standalone without instrumentation)', () => {
    jest.isolateModules(() => {
      const storage = require('@/core/lib/media/storage') as typeof import('@/core/lib/media/storage')
      const warn = jest.spyOn(console, 'warn').mockImplementation(() => {})
      storage.selectStorageDriver(env({ STORAGE_DRIVER: 'local', UPLOADS_DIR: '/data/uploads' }))
      storage.selectStorageDriver(env({ STORAGE_DRIVER: 'local', UPLOADS_DIR: '/data/uploads' }))
      expect(warn).toHaveBeenCalledTimes(1)
    })
  })

  it('logs a misconfiguration by variable name only', () => {
    const error = jest.spyOn(console, 'error').mockImplementation(() => {})
    logStorageAtStartup(env({ ...S3_ENV, S3_ENDPOINT: 'ftp://hidden-host' }))
    expect(error).toHaveBeenCalledWith(expect.stringContaining('S3_ENDPOINT is malformed'))
    expect(String(error.mock.calls[0][0])).not.toMatch(/hidden-host|very-secret|AKIDSECRET/)
  })

  it('warns about an http: S3 endpoint on another host', () => {
    const warn = jest.spyOn(console, 'warn').mockImplementation(() => {})
    logStorageAtStartup(env({ ...S3_ENV, S3_ENDPOINT: 'http://minio.internal:9000' }))
    expect(warn).toHaveBeenCalledWith(expect.stringContaining('S3_ENDPOINT uses http:'))
    expect(String(warn.mock.calls[0][0])).not.toContain('minio.internal')
    warn.mockClear()
    logStorageAtStartup(env(S3_ENV))
    expect(warn).not.toHaveBeenCalled()
  })

  it('says nothing when STORAGE_DRIVER is unset', () => {
    const warn = jest.spyOn(console, 'warn').mockImplementation(() => {})
    const error = jest.spyOn(console, 'error').mockImplementation(() => {})
    logStorageAtStartup(env({ NODE_ENV: 'production' }))
    expect(warn).not.toHaveBeenCalled()
    expect(error).not.toHaveBeenCalled()
  })
})
